/**
  * @brief  沿黑线走，出现拐角形态就停车返回（阻塞）
  *
  *  每一轮就干这几件事：
  *      ① 读五路 -> 模拟量算位置(mm) + 二值位图
  *      ② 兜底超时？
  *      ③ 拐角形态（外侧+内侧同时压黑）持续够久 -> 立刻停车返回
  *      ④ 看不到线 -> 保持上一次差速继续走，超时才停车返回
  *      ⑤ 否则 差速 = 查曲线(位置)，写电机
  */
int 巡线(int 速度)
{
    uint32_t 开始时刻 = HAL_GetTick();
    uint32_t 拐角开始 = 0U;
    uint32_t 丢线开始 = 0U;
#if 巡线_调试打印
    uint32_t 打印时刻 = 开始时刻;
#endif

    uint8_t  拐角中 = 0U;       /* 1 = 拐角形态正在连续出现 */
    uint8_t  丢线中 = 0U;       /* 1 = 正处在丢线保持状态 */
    uint8_t  已出角 = 0U;       /* 1 = 已出现过正常巡线形态，拐角判据解锁 */
    int      差速   = 0;        /* 上一次有效的差速（丢线时继续用它） */

    if (速度 > 100) 速度 = 100;
    if (速度 < 0)   速度 = 0;

    while (1)
    {
        uint16_t 原始值[巡线_路数];
        uint8_t  位图;
        uint8_t  有线;
        uint8_t  外侧黑;
        uint8_t  中间黑;
        uint8_t  拐角样;
        float    位置   = 0.0f;
        float    黑度和 = 0.0f;
        uint32_t 现在;

        /* ---- ① 采样：二值位图 + 模拟量位置 ---- */
        位图 = 巡线_读位图(原始值);
        有线 = 巡线_算位置(原始值, &位置, &黑度和);
        现在 = HAL_GetTick();

        /* ---- ② 兜底超时：任何情况下都不会永久卡死 ---- */
        if ((uint32_t)(现在 - 开始时刻) >= 巡线_最长毫秒)
        {
            巡线_上次结束原因 = 巡线_结束_超时;
            巡线_停车();
            return (int)(uint32_t)(现在 - 开始时刻);
        }

        /* ---- ③ 拐角形态 ----
           外侧两路（±60mm）正常巡线碰不到线，一压黑说明线拐到旁边去了；
           同时内侧 2/3/4 至少一路还压着，说明车正压在角上那段线上。 */
#if 巡线_外侧用强阈值
        外侧黑 = (((原始值[0] >= 灰度_各路强阈值[0]) ||
                   (原始值[4] >= 灰度_各路强阈值[4])) ? 1U : 0U);
#else
        外侧黑 = (((位图 & 0x01U) != 0U) || ((位图 & 0x10U) != 0U)) ? 1U : 0U;
#endif

        中间黑 = ((位图 & 0x0EU) != 0U) ? 1U : 0U;      /* bit1/bit2/bit3 */

        /* 解锁：先看到一次"线在中间、外侧没压线"的正常形态 */
        if (外侧黑 == 0U) {
            已出角 = 1U;
        }

#if 巡线_拐角用外侧加中间
        拐角样 = ((外侧黑 != 0U) && (中间黑 != 0U)) ? 1U : 0U;
#else
        {
            uint8_t 计数 = 0U, 临时 = 位图;

            while (临时 != 0U) {
                计数 = (uint8_t)(计数 + (临时 & 1U));
                临时 >>= 1;
            }
            拐角样 = (计数 >= 4U) ? 1U : 0U;
        }
#endif

        if ((已出角 != 0U) && (拐角样 != 0U))
        {
            if (拐角中 == 0U) {
                拐角中   = 1U;
                拐角开始 = 现在;
            } else if ((uint32_t)(现在 - 拐角开始) >= 巡线_拐角确认毫秒) {
                /* 到角了：立刻停（停位最准）。
                   别改成"先往前蹭再停"：那样车会被带进拐弯中途，定点停车就偏了。 */
                巡线_上次结束原因 = 巡线_结束_拐角;
                巡线_停车();
                return (int)(uint32_t)(现在 - 开始时刻);
            }
        }
        else
        {
            拐角中 = 0U;
        }

        /* ---- ④ 丢线 / ⑤ 查曲线 ---- */
        if (有线 == 0U)
        {
            if (丢线中 == 0U) {
                丢线中   = 1U;
                丢线开始 = 现在;
            } else if ((uint32_t)(现在 - 丢线开始) >= 巡线_丢线超时毫秒) {
                巡线_上次结束原因 = 巡线_结束_丢线;
                巡线_停车();
                return (int)(uint32_t)(现在 - 开始时刻);
            }
            /* 保持上一次的 差速 继续走：车会顺着最后的方向把线找回来 */
        }
        else
        {
            丢线中 = 0U;
            差速   = 巡线_查曲线(位置);
        }

        巡线_输出(速度, 差速);

        /* == 主屏幕刷新 ==
           注意这里**每轮都调**，不再自己按 100 ms 限速：回调必须是"发一小片
           就返回"的非阻塞版本（主屏幕_画一帧分片），一帧分几十次送完。
           以前是每 100 ms 调一次整帧刷新的阻塞版本，一次把 CPU 卡住 20~30 ms，
           车正好在那段时间里冲过路口。限速交给回调自己（见 menu_tree.c）。 */
        if (巡线_每帧回调 != NULL) {
            巡线_每帧回调();
        }

#if 巡线_调试打印
        巡线_打印(现在, &打印时刻, 原始值, 位图, 位置, 速度, 差速);
#endif
    }
}