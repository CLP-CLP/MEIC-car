/*  电机控制：按住上/下键连续增减，确认/返回键保存退出                   */
/* -------------------------------------------------------------------- */

static void 动作_设置左电机(void)
{
    int16_t 速度 = 灰度_左电机速度;
    char    行[20];

    for (;;) {
        OLED_清屏();
        OLED_显示中文串(0, 0, "左电机速度");
        (void)snprintf(行, sizeof(行), "%3d%%", (int)速度);
        OLED_显示ASCII串(46, 36, 行);
        OLED_刷新();

        电机_转速(电机_左, 速度);

        btn_event_t 事件 = 按键_取事件();
        if (事件 == BTN_SEL || 事件 == BTN_BACK) { break; }

        if (HAL_GPIO_ReadPin(BTN_PORT, BTN_UP_PIN) == GPIO_PIN_RESET && 速度 < 100) {
            速度++;
            灰度_左电机速度 = 速度;
        } else if (HAL_GPIO_ReadPin(BTN_PORT, BTN_DOWN_PIN) == GPIO_PIN_RESET && 速度 > 0) {
            速度--;
            灰度_左电机速度 = 速度;
        }
        HAL_Delay(20U);
    }
    电机_停止(电机_左);
    灰度_保存电机设置();
}

