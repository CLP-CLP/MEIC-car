/**
 ******************************************************************************
 * @file    menu_tree.c
 * @brief   菜单定义：菜单树 + 动作函数（引擎在 menu.c）
 *
 *  ─────────────────────────────────────────────────────────────────────
 *  为什么单独一个文件
 *      menu.c       纯引擎：三键导航、滚动、反白高亮、进栈出栈
 *      menu_tree.c  菜单定义：树长什么样、每一项干什么   ← 本文件
 *      想增/删/改菜单项，只改本文件，引擎一个字都不用动。
 *
 *  ─────────────────────────────────────────────────────────────────────
 *  怎么加菜单项（三步）
 *
 *   1) 写动作函数
 *          static void 动作_跑一圈(void) {
 *              菜单_提示("跑一圈", 600U);
 *              巡线(40);
 *              电机_全部停止();
 *          }
 *
 *   2) 如果要加新子菜单表，先在顶部"前向声明"区加一行：
 *          static const 菜单项 菜单_新表[];
 *
 *   3) 在对应菜单表里加一行
 *          菜单_命令("跑一圈", 动作_跑一圈),
 *
 *   表最后必须有 菜单_结束，否则引擎会一直往后读。
 *
 *  ─────────────────────────────────────────────────────────────────────
 *  前向声明：子菜单表可以写在**任何位置**，不再有顺序要求。
 *  新增子菜单表时，在这里加一行声明即可。
 *
 *  ─────────────────────────────────────────────────────────────────────
 *  菜单结构
 *      主菜单
 *        ├── 任务
 *        │     └── 巡线 / 循环 / 倒车入库 / 侧方停车 / 定点停车 / 检测停车 / 侦探
 *        ├── 调试
 *        │     ├── 巡线传感器读数
 *        │     ├── 灰度校准
 *        │     ├── 车库时间标定
 *        │     ├── 舵机调试
 *        │     └── 认卡测试
 *        ├── 控制
 *        │     └── 电机
 *        │           ├── 左电机速度
 *        │           └── 右电机速度
 *        └── 高级设置
 *              ├── 设置最低PWM
 *              └── 直接设置四路阈值
 ******************************************************************************
 */

