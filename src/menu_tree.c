static void 动作_原始值(void)
{
    char 行[20];

    for (;;) {
        uint8_t i;

        OLED_清屏();
        OLED_显示中文串(0, 0, 文本_原始值);
        for (i = 0U; i < 5U; i++) {
            uint16_t 原始值 = 巡线_读取第几路(i);
            int16_t  y      = (int16_t)(16 + i * 9);

            /* 左边留着原始数字：要看精确值就看这里 */
            (void)snprintf(行, sizeof(行), "c%u %4u", (unsigned)i, (unsigned)原始值);
            OLED_显示ASCII串(0, y, 行);

            /* 右边一条灰阶电平条：黑度越浓越亮，亮到一半就是判黑阈值，
               和主屏幕那五个框是同一套换算，两边对着看就能调阈值 */
            OLED_画矩形(60, y, 125, (int16_t)(y + 6), OLED_亮);
            OLED_填充灰阶矩形(61, (int16_t)(y + 1), 124, (int16_t)(y + 5),
                              灰度_黑度千分(i, 原始值));
        }
        OLED_刷新();

        if (按键_取事件() != BTN_NONE) { break; }
        HAL_Delay(120U);
    }
}

