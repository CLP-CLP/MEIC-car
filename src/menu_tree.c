/* ====================== 主屏幕：实时状态仪表板 ============================ */
/*
 *  上半：五路巡线传感器（黑 = 实心框，白 = 空心框）
 *  中部：左/右电机当前配置转速（0~100% 条形图）
 *  下半：当前任务名 + 步骤信息
 *
 *  按任意键退出，回到菜单
 */

static void 显示_主屏幕(void)
{
    uint16_t 原始[巡线_路数];
    uint8_t  i;
    int16_t  x0, 填充宽, 总宽;
    char     行[24];

    for (;;) {

        OLED_清屏();

        /* ---- 上半：五路传感器方块（y=2~15，每块 20×14） ---- */
        for (i = 0U; i < 巡线_路数; i++) {
            uint8_t 路 = 巡线_路数 - 1U - i;
            原始[路] = 巡线_读取第几路(路);
            x0 = (int16_t)(6 + i * 24);

            if (巡线_是否压线(原始[路], 灰度_各路阈值[路])) {
                OLED_填充矩形(x0, 2, (int16_t)(x0 + 19), 15, OLED_亮);
            } else {
                OLED_画矩形(x0, 2, (int16_t)(x0 + 19), 15, OLED_亮);
            }
        }

        /* ---- 中部：左/右电机转速条（并排，y=20~39） ---- */
        总宽 = 52;

        OLED_显示ASCII串(2,  20, "L");
        OLED_画矩形(8, 24, (int16_t)(8 + 总宽), 33, OLED_亮);
        填充宽 = (int16_t)((int32_t)总宽 * (int32_t)灰度_左电机速度 / 100);
        if (填充宽 > 0) {
            OLED_填充矩形(8, 24, (int16_t)(8 + 填充宽), 33, OLED_亮);
        }
        (void)snprintf(行, sizeof(行), "%3d%%", (int)灰度_左电机速度);
        OLED_显示ASCII串(8, 35, 行);

        OLED_显示ASCII串(64, 20, "R");
        OLED_画矩形(68, 24, (int16_t)(68 + 总宽), 33, OLED_亮);
        填充宽 = (int16_t)((int32_t)总宽 * (int32_t)灰度_右电机速度 / 100);
        if (填充宽 > 0) {
            OLED_填充矩形(68, 24, (int16_t)(68 + 填充宽), 33, OLED_亮);
        }
        (void)snprintf(行, sizeof(行), "%3d%%", (int)灰度_右电机速度);
        OLED_显示ASCII串(68, 35, 行);

        /* ---- 下半：任务名 + 步骤（y=48，中文 16px 高） ---- */
        if (主屏_任务名[0] != '\0') {
            (void)snprintf(行, sizeof(行), "%s %s", 主屏_任务名, 主屏_步信息);
            OLED_显示中文串(2, 48, 行);
        } else {
            OLED_显示中文串(2, 48, 文本_主屏幕);
        }

        OLED_刷新();

        if (按键_取事件() != BTN_NONE) { break; }
        HAL_Delay(80U);
    }
}

