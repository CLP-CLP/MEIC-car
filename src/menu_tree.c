/* ---- 跑车时的屏幕刷新预算 ------------------------------------------------ */
/*
 *  一帧 1024 字节走软件 I2C，整帧发完要 20~30 ms。以前是"每 100 ms 一口气
 *  发完"，也就是说车每 100 ms 就有 20~30 ms 既不看传感器也不发指令，
 *  正好在路口那一下被蒙住 —— 这就是"冲过路口"最主要的来源。
 *
 *  现在改成"细水长流"：每次巡线回环只发 主屏_刷新分片字节 个字节就走，
 *  一帧拆成几十次发完。总 CPU 占用不变，但最长一次蒙眼 < 1 ms。
 */
#define 主屏_运行刷新毫秒   100U    /* 跑车时每多少毫秒重新画一帧（0 = 不刷） */
#define 主屏_刷新分片字节   32U     /* 一次调用最多往 OLED 发多少字节 */

/** 1 = 上一帧还没送完，正在分片续传 */
static uint8_t  主屏_分片忙   = 0U;
/** 上一帧开始送的时刻（用来限速） */
static uint32_t 主屏_上次刷新 = 0U;

/**
  * @brief  只把主屏幕内容画进显存，不往 OLED 送（纳秒~百微秒级）
  */
static void 主屏_绘制(void)
{
    uint8_t  i;
    int16_t  x0, 填充宽, 总宽;
    char     行[24];

    OLED_清屏();

    /* ---- 五路传感器：抖动灰阶，不是黑白两态 ----
       原来的画法是"超过阈值就整个涂白，否则只画个空框"，只能看出压没压线；
       现在把每一路的**黑度**（0~1000，见 灰度_黑度千分）当灰度铺进框里：

           白底        -> 框里几乎全暗（淡）
           慢慢压上线  -> 框里的点越来越密，像铅笔越描越浓
           压住黑线    -> 框里几乎全亮
           正好 500    -> 一半的像素点亮 = 判黑阈值

       所以"框里比一半亮"就是压线，离阈值还差多少也一眼看得出来，
       比原来那个非黑即白的方块细得多。 */
    for (i = 0U; i < 巡线_路数; i++) {
        uint8_t  路 = 巡线_路数 - 1U - i;
        uint16_t 原始值 = 巡线_读取第几路(路);
        uint16_t 黑度   = 灰度_黑度千分(路, 原始值);

        x0 = (int16_t)(6 + i * 24);

        /* 框内（留 1 像素边框）铺灰阶 */
        OLED_填充灰阶矩形((int16_t)(x0 + 1), 3, (int16_t)(x0 + 18), 14, 黑度);

        /* 外框；判为压线时再套一圈内框加粗，保留原来的二值提示 */
        OLED_画矩形(x0, 2, (int16_t)(x0 + 19), 15, OLED_亮);
        if (巡线_是否压线(原始值, 灰度_各路阈值[路])) {
            OLED_画矩形((int16_t)(x0 + 1), 3, (int16_t)(x0 + 18), 14, OLED_亮);
        }
    }

    总宽 = 52;

    OLED_显示ASCII串(2,  20, "L");
    OLED_画矩形(8, 24, (int16_t)(8 + 总宽), 33, OLED_亮);
    填充宽 = (int16_t)((int32_t)总宽 * (int32_t)(电机_最后左速度 < 0 ? -电机_最后左速度 : 电机_最后左速度) / 100);
    if (填充宽 > 0) {
        OLED_填充矩形(8, 24, (int16_t)(8 + 填充宽), 33, OLED_亮);
    }
    (void)snprintf(行, sizeof(行), "%3d%%", (int)电机_最后左速度);
    OLED_显示ASCII串(8, 35, 行);

    OLED_显示ASCII串(64, 20, "R");
    OLED_画矩形(68, 24, (int16_t)(68 + 总宽), 33, OLED_亮);
    填充宽 = (int16_t)((int32_t)总宽 * (int32_t)(电机_最后右速度 < 0 ? -电机_最后右速度 : 电机_最后右速度) / 100);
    if (填充宽 > 0) {
        OLED_填充矩形(68, 24, (int16_t)(68 + 填充宽), 33, OLED_亮);
    }
    (void)snprintf(行, sizeof(行), "%3d%%", (int)电机_最后右速度);
    OLED_显示ASCII串(68, 35, 行);

    if (主屏_任务名[0] != '\0') {
        (void)snprintf(行, sizeof(行), "%s %s", 主屏_任务名, 主屏_步信息);
        OLED_显示中文串(2, 48, 行);
    } else {
        OLED_显示中文串(2, 48, 文本_主屏幕);
    }
}

void 主屏幕_画一帧(void)
{
    主屏_绘制();
    OLED_刷新();

    /* 整帧已经一次性送完，分片状态作废 */
    主屏_分片忙 = 0U;
}

void 主屏幕_画一帧分片(void)
{
    uint32_t 现在 = HAL_GetTick();

    /* 上一帧送完了，才考虑开新的一帧；并且按 主屏_运行刷新毫秒 限速 */
    if (主屏_分片忙 == 0U)
    {
        if ((uint32_t)(现在 - 主屏_上次刷新) < 主屏_运行刷新毫秒) {
            return;                     /* 还没到下次重画的时间，这一轮什么都不做 */
        }

        主屏_上次刷新 = 现在;
        主屏_绘制();                    /* 只写显存 */
        显示_开始刷新();                /* 打好窗口，准备一点一点发 */
        主屏_分片忙 = 1U;
    }

    /* 接着发一片。发完（返回 1）就等下一次重画 */
    if (显示_刷新分片(主屏_刷新分片字节) != 0U) {
        主屏_分片忙 = 0U;
    }
}

/* ====================== 主屏幕：实时状态仪表板 ============================ */
/*
 *  循环刷新传感器 + 电机转速 + 任务信息，按任意键退出。
 *  同时也作为菜单"主屏幕"菜单项的动作函数。
 *  注意：不在这里调用 菜单_运行()，菜单循环由 main.c 统一管理。
 */

void 显示_主屏幕(void)
{
    for (;;) {
        主屏幕_画一帧();
        if (按键_取事件() != BTN_NONE) { break; }
        HAL_Delay(80U);
    }
}

