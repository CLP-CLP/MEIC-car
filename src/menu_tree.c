static void 执行_循环(void)
{
    uint8_t 边;

    巡线_每帧回调 = 主屏幕_画一帧分片;
    转向_每帧回调 = 主屏幕_画一帧;
    for (边 = 0U; 边 < 4U; 边++) {
        (void)snprintf(主屏_步信息, sizeof(主屏_步信息), "%u/4", (unsigned)(边 + 1U));
        主屏幕_画一帧();
        巡线(40);
        电机_全部停止();
        HAL_Delay(200U);
        if (边 < 3U) { 左转(); }
    }
    巡线_每帧回调 = NULL;
    转向_每帧回调 = NULL;
    主屏_任务名 = "已完成";
    (void)snprintf(主屏_步信息, sizeof(主屏_步信息), "%s", 文本_循环);
}

