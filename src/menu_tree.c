/** 每按一次上下键挪几度 */
#define 舵机调试_步进       5

static void 动作_舵机调试(void)
{
    char    行[20];
    uint8_t 选中 = 0U;

    for (;;)
    {
        uint8_t i;

        OLED_清屏();

        /* 标题栏反白；右上角标出正在调哪一路 */
        OLED_填充矩形(0, 0, OLED_宽 - 1, 15, OLED_亮);
        OLED_显示中文串色(2, 0, 文本_舵机调试, OLED_灭);
        (void)snprintf(行, sizeof(行), "S%u", (unsigned)(选中 + 1U));
        OLED_显示ASCII串色(112, 4, 行, OLED_灭);

        /* 两路的角度；选中那行套个框 */
        for (i = 0U; i < 舵机_数量; i++)
        {
            int16_t 行顶 = (int16_t)(16 + i * 16);

            if (i == 选中) {
                OLED_画矩形(0, 行顶, OLED_宽 - 1, (int16_t)(行顶 + 15), OLED_亮);
            }

            (void)snprintf(行, sizeof(行), "%u: %3d",
                           (unsigned)(i + 1U), (int)舵机_角度[i]);
            OLED_显示ASCII串(2, (int16_t)(行顶 + 4), 行);
        }

        OLED_显示中文串(2, 48, 文本_舵机提示);
        OLED_刷新();

        /* ---- 按键 ---- */
        {
            btn_event_t 事件 = 按键_取事件();

            if (事件 == BTN_UP) {
                舵机_设置角度((舵机_编号)选中, (int16_t)(舵机_角度[选中] + 舵机调试_步进));
            } else if (事件 == BTN_DOWN) {
                舵机_设置角度((舵机_编号)选中, (int16_t)(舵机_角度[选中] - 舵机调试_步进));
            } else if (事件 == BTN_SEL) {
                选中 = (uint8_t)((选中 + 1U) % 舵机_数量);      /* 换一路调 */
            } else if (事件 == BTN_BACK) {
                break;                                          /* 长按退出 */
            }
        }

        /* 刷一帧要 25 ms 左右，这里再歇一下就够了：按键状态机 1 ms 轮询一次
           也来得及，但没必要把 CPU 全烧在刷屏上 */
        HAL_Delay(20U);
    }

    /* 退出时把两个舵机留在中位，免得云台歪着 */
    舵机_全部中位();
}

