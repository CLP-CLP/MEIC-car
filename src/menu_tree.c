/**
  * @brief  逐路设置灰度阈值：上/下调值，确认进下一路，五路设完自动保存
  */
static void 动作_直接设置四路阈值(void)
{
    uint16_t 值[巡线_路数];
    uint8_t  通道 = 0U;
    uint8_t  已修改 = 0U;
    char     行[20];
    uint8_t  i;

    for (i = 0U; i < 巡线_路数; i++) {
        值[i] = 灰度_各路阈值[i];
    }

    for (;;) {
        OLED_清屏();
        (void)snprintf(行, sizeof(行), "通道%u/5", (unsigned)(通道 + 1U));
        OLED_显示中文串(0, 0, 行);
        (void)snprintf(行, sizeof(行), "%4u", (unsigned)值[通道]);
        OLED_显示ASCII串(40, 36, 行);
        OLED_刷新();

        btn_event_t 事件 = 按键_取事件();
        if (事件 == BTN_SEL) {
            通道++;
            if (通道 >= 巡线_路数) { break; }
        } else if (事件 == BTN_BACK) {
            break;
        }

        if (HAL_GPIO_ReadPin(BTN_PORT, BTN_UP_PIN) == GPIO_PIN_RESET && 值[通道] < 4095U) {
            值[通道] += 10U;
            已修改 = 1U;
        } else if (HAL_GPIO_ReadPin(BTN_PORT, BTN_DOWN_PIN) == GPIO_PIN_RESET && 值[通道] >= 10U) {
            值[通道] -= 10U;
            已修改 = 1U;
        }
        HAL_Delay(30U);
    }

    if (已修改 != 0U) {
        for (i = 0U; i < 巡线_路数; i++) {
            灰度_各路阈值[i] = 值[i];
        }
    }
}

