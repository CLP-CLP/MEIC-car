/**
  ******************************************************************************
  * @file    servo.c
  * @brief   两路舵机 PWM 输出（PB8 = TIM4_CH3 / PB9 = TIM4_CH4）
  *
  *  ── 怎么产生 50 Hz ──
  *      TIM4 挂在 APB1 上，本工程 APB1 预分频 = 2，所以定时器时钟 = 72 MHz
  *      （APB1 分频不为 1 时，定时器时钟自动 ×2）。
  *
  *          预分频 71  ->  72 MHz / 72 = 1 MHz，一格 1 µs
  *          自动重装 19999 -> 20000 格 = 20 ms = 50 Hz
  *
  *      于是比较值 CCR 直接就是"高电平多少微秒"，不用再做任何换算：
  *          CCR = 500   -> 0.5 ms  -> 0°
  *          CCR = 1500  -> 1.5 ms  -> 90°（中位）
  *          CCR = 2500  -> 2.5 ms  -> 180°
  *
  *  ── 为什么不用电机那个 TIM3 ──
  *      电机 PWM 是 20 kHz（为了不啸叫），舵机要 50 Hz，差 400 倍，
  *      一个定时器没法同时出这两种频率（改 ARR 会让电机的频率也变）。
  *
  *  ⚠ 本文件使用中文标识符（UTF-8），需要 GCC 10 及以上。
  *     凡是以 HAL_ 开头的固定接口名一律保持英文。
  ******************************************************************************
  */

/* Includes ------------------------------------------------------------------*/
#include "main.h"
#include "servo.h"

/* ============================== 私有数据 =================================== */

/** TIM4 句柄（本模块私有） */
static TIM_HandleTypeDef 舵机_定时器;

/** 两路对应的定时器通道，下标 = 舵机_编号 */
static const uint32_t 舵机_通道表[舵机_数量] =
{
    舵机_水平_通道,
    舵机_垂直_通道,
};

/** 当前角度，供菜单/调试页显示 */
int16_t 舵机_角度[舵机_数量] = { 舵机_水平_中位角度, 舵机_垂直_中位角度 };

/* ============================== 函数实现 =================================== */

void 舵机_初始化(void)
{
    TIM_OC_InitTypeDef 输出比较 = {0};

    舵机_定时器.Instance               = 舵机_定时器编号;
    舵机_定时器.Init.Prescaler         = 舵机_预分频;
    舵机_定时器.Init.CounterMode       = TIM_COUNTERMODE_UP;
    舵机_定时器.Init.Period            = 舵机_自动重装值;
    舵机_定时器.Init.ClockDivision     = TIM_CLOCKDIVISION_DIV1;
    舵机_定时器.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_DISABLE;

    /* HAL_TIM_PWM_Init() 内部会调用 HAL_TIM_PWM_MspInit()：
       使能 TIM4 / GPIOB 时钟，并把 PB8 / PB9 配成复用推挽输出 */
    if (HAL_TIM_PWM_Init(&舵机_定时器) != HAL_OK) {
        Error_Handler();
    }

    输出比较.OCMode     = TIM_OCMODE_PWM1;
    输出比较.Pulse      = 0U;                       /* 先给 0，别让上电瞬间乱甩 */
    输出比较.OCPolarity = TIM_OCPOLARITY_HIGH;
    输出比较.OCFastMode = TIM_OCFAST_DISABLE;

    if (HAL_TIM_PWM_ConfigChannel(&舵机_定时器, &输出比较, 舵机_水平_通道) != HAL_OK) {
        Error_Handler();
    }
    if (HAL_TIM_PWM_ConfigChannel(&舵机_定时器, &输出比较, 舵机_垂直_通道) != HAL_OK) {
        Error_Handler();
    }

    if (HAL_TIM_PWM_Start(&舵机_定时器, 舵机_水平_通道) != HAL_OK) {
        Error_Handler();
    }
    if (HAL_TIM_PWM_Start(&舵机_定时器, 舵机_垂直_通道) != HAL_OK) {
        Error_Handler();
    }

    /* 上电就给一个确定的位置：不给的话舵机没收到信号会软掉，云台自己乱晃 */
    舵机_设置角度(舵机_水平, 舵机_水平_中位角度);
    舵机_设置角度(舵机_垂直, 舵机_垂直_中位角度);
}

void 舵机_设置脉宽(舵机_编号 哪台, uint16_t 微秒)
{
    if ((uint32_t)哪台 >= 舵机_数量) {
        return;
    }

    if (微秒 < 舵机_最小脉宽) { 微秒 = 舵机_最小脉宽; }
    if (微秒 > 舵机_最大脉宽) { 微秒 = 舵机_最大脉宽; }

    __HAL_TIM_SET_COMPARE(&舵机_定时器, 舵机_通道表[哪台], (uint32_t)微秒);

    /* 角度按当前标定反算一下，别让显示和实际对不上
       （用别的脉宽范围跑 270° 舵机时，这里算出来的"度"就只是参考值） */
    舵机_角度[哪台] = (int16_t)(((uint32_t)(微秒 - 舵机_最小脉宽) * 舵机_角度上限)
                                / (舵机_最大脉宽 - 舵机_最小脉宽));
}

void 舵机_设置角度(舵机_编号 哪台, int16_t 角度)
{
    uint32_t 微秒;
    int16_t  最小, 最大;

    if ((uint32_t)哪台 >= 舵机_数量) {
        return;
    }

    /* 每路舵机有不同的物理限位，先夹到允许范围内 */
    if (哪台 == 舵机_水平) {
        最小 = 舵机_水平_最小角度;
        最大 = 舵机_水平_最大角度;
    } else {
        最小 = 舵机_垂直_最小角度;
        最大 = 舵机_垂直_最大角度;
    }

    if (角度 < 最小) { 角度 = 最小; }
    if (角度 > 最大) { 角度 = 最大; }

    微秒 = 舵机_最小脉宽
         + ((uint32_t)角度 * (舵机_最大脉宽 - 舵机_最小脉宽)) / (uint32_t)舵机_角度上限;

    舵机_设置脉宽(哪台, (uint16_t)微秒);
}

void 舵机_全部中位(void)
{
    舵机_设置角度(舵机_水平, 舵机_水平_中位角度);
    舵机_设置角度(舵机_垂直, 舵机_垂直_中位角度);
}