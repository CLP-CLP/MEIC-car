/**
 ******************************************************************************
 * @file    detective.c
 * @brief   自定义任务：巡线到横线，按耗时分辨车库类型
 *
 *  沿边巡线到车库门口 -> 用标定好的时间做最近邻匹配，
 *  分辨是 40 cm 车库（倒库）还是 25 cm 车库（侧方）。
 ******************************************************************************
 */

/* Includes ------------------------------------------------------------------*/
#include "detective.h"

#include "garage_calib.h"       /* 侦探_走到横线() */
#include "gray_calib.h"         /* 灰度_取车库时间() */
#include "motor.h"
#include "park_back.h"          /* 倒库() / 侧方停车() */

#include <stdio.h>

void detective(void)
{
    uint16_t 车库40毫秒 = 0U;
    uint16_t 车库25毫秒 = 0U;
    int      经过时间;
    int      差40;
    int      差25;

    HAL_Delay(2000U);

    经过时间 = 侦探_走到横线();

    if (经过时间 < 0) {                  /* 用户长按确认急停了 */
        电机_全部停止();
        return;
    }

    if (灰度_取车库时间(&车库40毫秒, &车库25毫秒) != 0U)
    {
        /* 和哪个标定值更接近，就是哪种车库 —— 比"和中间值比大小"更稳，
           也不依赖"40 cm 一定比 25 cm 走得久"这个假设。 */
        差40 = (经过时间 > (int)车库40毫秒) ? (经过时间 - (int)车库40毫秒)
                                            : ((int)车库40毫秒 - 经过时间);
        差25 = (经过时间 > (int)车库25毫秒) ? (经过时间 - (int)车库25毫秒)
                                            : ((int)车库25毫秒 - 经过时间);

        printf("detective: %d ms (40cm=%u d=%d, 25cm=%u d=%d) -> %s\r\n",
               经过时间, (unsigned)车库40毫秒, 差40,
               (unsigned)车库25毫秒, 差25,
               (差40 <= 差25) ? "BACK-IN (40cm)" : "PARALLEL (25cm)");

        if (差40 <= 差25) {
            倒库();
        } else {
            侧方停车();
        }
    }
    else
    {
        /* 还没做过车库时间标定：退回原来的经验阈值，别让车直接不认路 */
        printf("detective: %d ms, no garage calibration -> fallback 1000 ms\r\n", 经过时间);

        if (经过时间 > 1000) {
            倒库();
        } else {
            侧方停车();
        }
    }
}