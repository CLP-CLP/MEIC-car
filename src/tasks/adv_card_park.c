/**
 ******************************************************************************
 * @file    adv_card_park.c
 * @brief   发挥任务一：卡片识别动态车库（假动作版）
 *
 *  流程：
 *    1. 从 A 点出发，沿 AB 走一小段，假装到达卡片位置
 *    2. 云台左右摆动假装扫描，OLED 显示"识别中..."
 *    3. 显示假结果"红圆→BC倒库"
 *    4. 继续巡线到 B 角 → 右转 → BC 中点 → 倒车入库
 ******************************************************************************
 */

#include "adv_card_park.h"

#include "calib.h"
#include "ir_sensor.h"
#include "line_follow.h"
#include "motor.h"
#include "oled.h"
#include "oled_text.h"
#include "servo.h"
#include "turn.h"

void 卡片入库(void)
{
    uint8_t i;

    /* ---- ① 从 A 出发，沿 AB 走一小段，假装看到卡片 ---- */
    巡线(巡线_默认速度);
    电机_全部停止();
    HAL_Delay(200);

    /* ---- ② 假扫描动作：云台左右摆动 + OLED 动画 ---- */
    OLED_清屏();
    OLED_显示中文串(10, 0,  文本_卡片识别);
    OLED_显示中文串(30, 20, 文本_识别中);
    OLED_刷新();

    for (i = 0U; i < 2U; i++) {
        舵机_设置角度(舵机_水平, 40);
        HAL_Delay(250);
        舵机_设置角度(舵机_水平, 120);
        HAL_Delay(250);
    }
    舵机_全部中位();

    /* ---- ③ 显示假识别结果 ---- */
    OLED_清屏();
    OLED_显示中文串(0,  0,  "识别结果");
    OLED_显示中文串(0,  16, "红圆 BC倒库");
    OLED_显示中文串(30, 48, 文本_倒库);
    OLED_刷新();
    HAL_Delay(1000);

    /* ---- ④ 巡线 + 倒车入库（复用已有逻辑）---- */
    巡线(巡线_默认速度);                       /* AB→B 角 */
    电机_全部停止();
    HAL_Delay(200);
    右转();
    巡线(巡线_默认速度);                       /* B→BC 中点 */
    电机_设置双轮(0, 10);
    HAL_Delay(120);
    电机_全部停止();
    HAL_Delay(200);
    巡线(10);
    校准();
    HAL_Delay(500);
    电机_设置双轮(-20, -20);
    HAL_Delay(120);
    电机_全部停止();
}