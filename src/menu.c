/**
 ******************************************************************************
 * @file    menu.c
 * @brief   二级菜单（Marlin 风格）：
 *          三键（上/下/确认）+ OLED 中文显示 + 表驱动
 *
 *  流程
 *      上电 -> 菜单_运行() -> 初始化按键/OLED -> 显示主菜单
 *           -> 上/下键移动光标
 *           -> 确认键（短按）进入子菜单
 *           -> 子菜单：[运行] 执行任务 / [返回] 回到主菜单
 *           -> 确认键（长按 2s）任意层级返回
 *
 *  ┌─────────────────────────────────────────────────────────────┐
 *  │  界面布局（OLED 128x64，16×16 中文字符）                     │
 *  │                                                             │
 *  │  Row 0-1 : 标题（16×16 中文，居中）                          │
 *  │  Row 2-3 : 菜单项 0                                         │
 *  │  Row 4-5 : 菜单项 1      最多同时显示 3 项，多了自动滚动     │
 *  │  Row 6-7 : 菜单项 2      右侧有 ^ / v 滚动提示               │
 *  │                                                             │
 *  │  加新选项：只在 菜单表[] 里加一行即可。                      │
 *  └─────────────────────────────────────────────────────────────┘
 ******************************************************************************
 */

