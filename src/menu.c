/* ============================== 布局常量 =================================== */
/*
 *  坐标一律用 8x8 字符格为单位，避免魔术数字：
 *      像素 y = 行号 * 8      像素 x = 列号 * 8
 */

#define 布局_标题行         0U      /* 标题占 行 0..1 */
#define 布局_首项行         2U      /* 第 0 项占 行 2..3 */
#define 布局_每项行数       2U      /* 每项 2 行 = 16 像素 */
#define 布局_可见项数       3U      /* 一屏 3 项 = 行 2..7 */

#define 布局_标签列         1U      /* 菜单项文字起始列 */

/* 选中框：左右边界按**字模墨迹实测**内缩，避免边框切过汉字笔画 */
#define 布局_框左边距       2U      /* 最左笔画再往左 2 像素 */
#define 布局_框右边距       2U      /* 最右笔画再往右 2 像素 */
#define 布局_框上边距       1U      /* 行顶往下 1 像素 */
#define 布局_框下边距       1U      /* 行底往上 1 像素 */

/** 行号 -> 该行顶部的像素 y */
#define 布局_行像素(行)     ((uint8_t)((行) * 8U))

/** 滚动提示箭头所在列（最右一列） */
#define 布局_箭头列         (显示_列数 - 1U)

/* ============================== UTF-8 小工具 =============================== */

/** 数 UTF-8 串的字符个数（一个汉字算 1，不是 3 个字节） */
static uint8_t 文本_字符数(const char *串)
{
    uint8_t n = 0U;

    while (*串 != '\0')
    {
        uint8_t c = (uint8_t)*串;
        串 += ((c < 0x80U) ? 1U : (((c & 0xE0U) == 0xC0U) ? 2U : 3U));
        n++;
    }
    return n;
}

/** 按 UTF-8 字符安全截断（不会把汉字切一半） */
static void 文本_截断(const char *源, char *输出, uint8_t 输出大小, uint8_t 最大字符数)
{
    uint8_t 已用 = 0U;
    uint8_t 个数 = 0U;

    while (*源 != '\0' && 个数 < 最大字符数)
    {
        uint8_t c = (uint8_t)*源;
        uint8_t 步进 = ((c < 0x80U) ? 1U : (((c & 0xE0U) == 0xC0U) ? 2U : 3U));
        uint8_t j;

        if (((uint16_t)已用 + 步进 + 1U) > 输出大小) {
            break;
        }
        for (j = 0U; j < 步进 && *源 != '\0'; j++) {
            输出[已用++] = *源++;
        }
        个数++;
    }
    输出[已用] = '\0';
}

/* ============================== 画界面 ===================================== */

/**
  * @brief  画一屏菜单
  * @param  标题      顶部标题（UTF-8，按字符数居中）
  * @param  项名      菜单项名字数组
  * @param  总项数    数组长度
  * @param  选中      当前选中下标
  * @param  可见项数  一屏显示几项
  */
static void 菜单_画界面(const char *标题,
                        const char *const 项名[],
                        uint8_t 总项数,
                        uint8_t 选中,
                        uint8_t 可见项数)
{
    uint8_t 首项 = 0U;
    uint8_t i;
    uint8_t 标题字符数;
    uint8_t 标题列;

    /* ---- 滚动窗口：让选中项始终留在屏内 ---- */
    if (可见项数 > 总项数) {
        可见项数 = 总项数;
    }
    if (总项数 > 可见项数)
    {
        if (选中 >= 可见项数) {
            首项 = (uint8_t)(选中 - (可见项数 - 1U));
        }
        if (((uint16_t)首项 + 可见项数) > 总项数) {
            首项 = (uint8_t)(总项数 - 可见项数);
        }
    }

    显示_清屏();

    /* ---- 标题：按字符数居中（汉字占 2 列，ASCII 占 1 列）---- */
    标题字符数 = 文本_字符数(标题);
    if (标题字符数 > (显示_列数 / 2U)) {
        标题字符数 = (uint8_t)(显示_列数 / 2U);      /* 最多 8 个汉字宽 */
    }
    标题列 = (uint8_t)((显示_列数 - ((uint16_t)标题字符数 * 2U)) / 2U);
    显示_画中文(标题列, 布局_标题行, 标题);

    /* ---- 菜单项 ---- */
    for (i = 0U; i < 可见项数; i++)
    {
        uint8_t 项 = (uint8_t)(首项 + i);
        uint8_t 行 = (uint8_t)(布局_首项行 + i * 布局_每项行数);

        if (项 >= 总项数) {
            break;
        }
        显示_画中文(布局_标签列, 行, 项名[项]);
    }

    /* ---- 选中框：左右边界按文字**实测墨水宽度**来，边框不切笔画 ---- */
    {
        uint8_t 选中行 = (uint8_t)(布局_首项行 + (选中 - 首项) * 布局_每项行数);
        uint8_t y顶 = (uint8_t)(布局_行像素(选中行) + 布局_框上边距);
        uint8_t y底 = (uint8_t)(布局_行像素((uint8_t)(选中行 + 布局_每项行数))
                                - 1U - 布局_框下边距);
        uint8_t 文字左 = (uint8_t)(布局_标签列 * 8U);
        uint8_t 文字宽 = 显示_文字像素宽(项名[选中]);
        uint8_t x左;
        uint8_t x右;

        /* 左边让开：不能小于 0 */
        x左 = (文字左 > 布局_框左边距) ? (uint8_t)(文字左 - 布局_框左边距) : 0U;

        /* 右边让开：不能超过屏幕右边界 */
        {
            uint16_t 候选 = (uint16_t)文字左 + 文字宽 + 布局_框右边距 - 1U;
            x右 = (候选 > (显示_宽度 - 1U)) ? (uint8_t)(显示_宽度 - 1U) : (uint8_t)候选;
        }

        显示_画空心框(x左, y顶, x右, y底);
    }

    /* ---- 滚动提示 ---- */
    if (首项 > 0U) {
        显示_画字符(布局_箭头列, 布局_首项行, '^');
    }
    if (((uint16_t)首项 + 可见项数) < 总项数) {
        显示_画字符(布局_箭头列,
                    (uint8_t)(布局_首项行 + (可见项数 - 1U) * 布局_每项行数 + 1U),
                    'v');
    }

    显示_刷新();
}

/** 子菜单界面：用一级项名做标题 + [运行]/[返回] */
static void 菜单_画子界面(uint8_t 主选中, uint8_t 子选中)
{
    char 标题[16];

    文本_截断(菜单表[主选中].名字, 标题, (uint8_t)sizeof(标题), 4U);
    菜单_画界面(标题, 子菜单_项名, 子菜单_项数, 子选中, 子菜单_项数);
}

/* ============================== 导航 ======================================= */

/** 上/下循环移动光标 */
static uint8_t 菜单_导航(uint8_t 当前, uint8_t 总数, btn_event_t 事件)
{
    if (总数 == 0U) {
        return 0U;
    }
    if (事件 == BTN_UP) {
        return (当前 == 0U) ? (uint8_t)(总数 - 1U) : (uint8_t)(当前 - 1U);
    }
    if (事件 == BTN_DOWN) {
        return (uint8_t)((当前 + 1U) % 总数);
    }
    return 当前;
}

/* ============================== 执行动作 =================================== */

static void 菜单_执行动作(const 菜单_项 *项)
{
    显示_清屏();
    显示_画中文(0, 2, 项->名字);
    显示_画中文(2, 4, "运行中");
    显示_刷新();

    if (项->动作 != NULL) {
        项->动作();
    }
}

/* ============================== 原始值显示 ================================= */

/** 画 4 位十进制数（不依赖 printf，省 Flash） */
static void 菜单_画数字(uint8_t 列, uint8_t 行, uint16_t 数值)
{
    char 缓冲[5];

    缓冲[0] = (char)('0' + ((数值 / 1000U) % 10U));
    缓冲[1] = (char)('0' + ((数值 / 100U) % 10U));
    缓冲[2] = (char)('0' + ((数值 / 10U) % 10U));
    缓冲[3] = (char)('0' + (数值 % 10U));
    缓冲[4] = '\0';
    显示_画字符串(列, 行, 缓冲);
}

static void 菜单_读五路(uint16_t *值)
{
    uint8_t i;
    for (i = 0U; i < 5U; i++) {
        值[i] = 巡线_读取第几路(i);
    }
}

/** 5 路 raw 实时界面：行 0-1 标题，行 2..6 五路，行 7 提示 */
static void 菜单_画原始值界面(const uint16_t *值)
{
    uint8_t i;

    显示_清屏();
    显示_画中文(5, 0, "原始值");
    for (i = 0U; i < 5U; i++)
    {
        char 标签[4];
        uint8_t 行 = (uint8_t)(2U + i);

        标签[0] = 'c';
        标签[1] = (char)('0' + i);
        标签[2] = ':';
        标签[3] = '\0';
        显示_画字符串(0, 行, 标签);
        菜单_画数字(3, 行, 值[i]);
    }
}

static void 菜单_显示原始值(void)
{
    uint16_t 值[5];

    while (1)
    {
        菜单_读五路(值);
        菜单_画原始值界面(值);
        显示_画字符串(0, 7, "ANY KEY=EXIT");
        显示_刷新();

        if (按键_取事件() != BTN_NONE) {
            break;
        }
        HAL_Delay(150U);
    }
}

/* ============================== 串口标定 =================================== */

void 菜单_串口标定(void)
{
    uint16_t 值[5];

    显示_初始化();
    printf("\r\n===== 5-way IR raw values (0-4095) =====\r\n");

    while (1)
    {
        菜单_读五路(值);
        printf("c0=%4u c1=%4u c2=%4u c3=%4u c4=%4u\r\n",
               (unsigned)值[0], (unsigned)值[1], (unsigned)值[2],
               (unsigned)值[3], (unsigned)值[4]);

        菜单_画原始值界面(值);
        显示_画字符串(0, 7, "SERIAL MODE");
        显示_刷新();
        HAL_Delay(200U);
    }
}

/* ============================== 动作包装 =================================== */

static void 跑直线(void)
{
    巡线(40);
    电机_全部停止();
}

static void 跑循环(void)
{
    uint8_t i;
    for (i = 0U; i < 4U; i++)
    {
        巡线(40);
        左转();
    }
    电机_全部停止();
}

/* ============================== 主入口 ===================================== */

void 菜单_运行(void)
{
    uint8_t 主选中 = 0U;
    uint8_t 子选中 = 0U;
    uint8_t 在子菜单 = 0U;

    按键_初始化();
    显示_初始化();

    菜单_画界面("功能菜单", (const char *const *)菜单表, 菜单_项数,
                主选中, 布局_可见项数);

    while (1)
    {
        btn_event_t 事件 = 按键_取事件();

        if (事件 == BTN_NONE)
        {
            HAL_Delay(10U);
            continue;
        }

        /* ---- 长按确认键 = 返回上一级 ---- */
        if (事件 == BTN_BACK)
        {
            if (在子菜单 != 0U)
            {
                在子菜单 = 0U;
                子选中 = 0U;
                菜单_画界面("功能菜单", (const char *const *)菜单表, 菜单_项数,
                            主选中, 布局_可见项数);
            }
            continue;
        }

        if (在子菜单 == 0U)
        {
            /* ========== 一级菜单 ========== */
            uint8_t 新选中 = 菜单_导航(主选中, 菜单_项数, 事件);

            if (新选中 != 主选中)
            {
                主选中 = 新选中;
                菜单_画界面("功能菜单", (const char *const *)菜单表, 菜单_项数,
                            主选中, 布局_可见项数);
            }
            else if (事件 == BTN_SEL)
            {
                在子菜单 = 1U;
                子选中 = 0U;
                菜单_画子界面(主选中, 子选中);
            }
        }
        else
        {
            /* ========== 子菜单 ========== */
            uint8_t 新选中 = 菜单_导航(子选中, 子菜单_项数, 事件);

            if (新选中 != 子选中)
            {
                子选中 = 新选中;
                菜单_画子界面(主选中, 子选中);
            }
            else if (事件 == BTN_SEL)
            {
                if (子选中 == 0U)
                {
                    菜单_执行动作(&菜单表[主选中]);
                    子选中 = 0U;
                    菜单_画子界面(主选中, 子选中);
                }
                else
                {
                    在子菜单 = 0U;
                    子选中 = 0U;
                    菜单_画界面("功能菜单", (const char *const *)菜单表, 菜单_项数,
                                主选中, 布局_可见项数);
                }
            }
        }

        HAL_Delay(10U);
    }
}
