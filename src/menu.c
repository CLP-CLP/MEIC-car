/* ============================== 对外接口 =================================== */

void 菜单_复位(void)
{
    菜单_深度 = 1U;
    菜单_栈[0] = 菜单_主;
    菜单_标题栈[0] = 文本_主菜单;
    菜单_选中 = 0U;
    菜单_首项 = 0U;
}

void 菜单_运行(void)
{
    按键_初始化();
    OLED_初始化();
    菜单_复位();
    菜单_重画();

    for (;;)
    {
        btn_event_t 事件 = 按键_取事件();

        if (事件 != BTN_NONE) {
            菜单_处理(事件);
        }

        HAL_Delay(10U);                         /* 10 ms 轮询，按下去就有反应 */
    }
}
