/**
  ******************************************************************************
  * @file    menu.c
  * @brief   菜单：按键选择功能 + OLED 显示 + 启动任务（表驱动，加选项只加一行）
  *
  *  流程
  *      上电 -> 菜单_运行() -> 初始化按键/OLED -> 显示菜单
  *            -> 短按【选择】循环选功能，长按 2 秒【确认】运行 -> 跑完回菜单
  *
  *  ┌────────────────────────────────────────────────────────────────────────┐
  *  │  怎么加新选项：只在下面的 菜单表[] 里加一行，其它地方一个字都不用改。  │
  *  │                                                                        │
  *  │      { "8.My Thing",  我的动作函数 },                                  │
  *  │            ↑名字          ↑动作                                        │
  *  └────────────────────────────────────────────────────────────────────────┘
  *
  *  名字：OLED 是 8x8 ASCII 字库，只能英文/数字/符号，最长 15 个字符
  *        （第 0 列留给 '>' 选中箭头，所以从第 1 列开始显示）。
  *  动作：写现成的函数名就行，例如 左转 / 右转 / 灰度_校准 / 倒库；
  *        需要传参数的（比如"用 40 的速度巡线"）就照 跑直线() 那样在本文件里
  *        包一层小函数，再把函数名填进表里。
  *
  *  选项超过 6 个会自动滚动，右侧出现 ^ / v 箭头，不用改显示代码。
  *  顺序 = 表里的顺序，选中项从表头开始；删掉一行也只是少一个选项。
  ******************************************************************************
  */

