/* ============================== 私有函数声明 =============================== */

static void 菜单_显示原始值(void);
static void 跑直线(void);
static void 跑循环(void);

/* ============================== 菜单表 ===================================== */
/*
 *   加/删/改选项全部只动这张表。
 *   第一列 = OLED 上显示的中文名，第二列 = 确认运行时调用的函数。
 */

typedef struct
{
    const char *名字;           /*!< OLED 上显示的中文名称（16×16 渲染） */
    void      (*动作)(void);    /*!< 确认运行后调用 */
} 菜单_项;

static const 菜单_项 菜单表[] =
{
    /*  名字        动作              说明 */
    { "巡线",       跑直线          },      /* 巡线一直走 */
    { "循环",       跑循环          },      /* 巡线 + 右转 ×4 */
    { "倒库",       倒库            },      /* 倒车入库 */
    { "侧停",       侧方停车        },      /* 侧方停车 */
    { "定点",       任务三_定点停车 },      /* 定点停车 */
    { "检测",       巡线检测停车    },      /* 巡线 + 检测停车 */
    { "原始值",     菜单_显示原始值 },      /* 5 路 raw 实时显示 */
    { "侦探",       detective       },      /* detective */

    /* ---- 加选项照下面格式加一行即可 ------------------------------------ */
    /* { "左转",     左转            }, */
};

/** 表里有多少项 */
#define 菜单_项数       ((uint8_t)(sizeof(菜单表) / sizeof(菜单表[0])))

/* ============================== 子菜单 ===================================== */

/** 子菜单固定两项 */
static const char *子菜单_项名[] = { "运行", "返回" };
#define 子菜单_项数     2U

/* ============================== 界面布局 =================================== */
/*
 *  OLED 是 16 列 × 8 行字符网格（8×8 为单位）：
 *      16×16 中文字符 = 2 列 × 2 行
 *      Row 0-1 : 标题（16×16，居中）
 *      Row 2-7 : 3 个菜单项（每个 2 行）
 */
#define 主菜单_首行         2U
#define 主菜单_可见项数     3U

/* ============================== 画数字 ===================================== */

static void 菜单_画数字(uint8_t 列, uint8_t 行, uint16_t 数值)
{
    char 缓冲[5];
    缓冲[0] = (char)('0' + ((数值 / 1000U) % 10U));
    缓冲[1] = (char)('0' + ((数值 / 100U) % 10U));
    缓冲[2] = (char)('0' + ((数值 / 10U) % 10U));
    缓冲[3] = (char)('0' + (数值 % 10U));
    缓冲[4] = '\0';
    显示_画字符串(列, 行, 缓冲);
}

static void 菜单_画原始值界面(const uint16_t *值)
{
    uint8_t i;
    显示_清屏();
    显示_画中文(4, 0, "原始值");
    for (i = 0U; i < 5U; i++)
    {
        char 标签[4];
        uint8_t 行 = (uint8_t)(2U + i);
        标签[0] = 'c';
        标签[1] = (char)('0' + i);
        标签[2] = ':';
        标签[3] = '\0';
        显示_画字符串(0, 行, 标签);
        菜单_画数字(3, 行, 值[i]);
    }
}

static void 菜单_读五路(uint16_t *值)
{
    uint8_t i;
    for (i = 0U; i < 5U; i++) {
        值[i] = 巡线_读取第几路(i);
    }
}

/* ============================== 菜单绘制 =================================== */

/**
  * @brief  绘制通用菜单界面
  * @param  标题      顶部标题（16×16 中文，会自动居中）
  * @param  项名数组  菜单项名称数组（const char *[]）
  * @param  总项数    项名数组长度
  * @param  选中      当前选中下标
  * @param  可见项数  一屏最多显示几项
  * @param  首行      第一项的起始行（8×8 网格坐标）
  */
static void 菜单_画界面(const char *标题,
                        const char *const 项名[],
                        uint8_t 总项数,
                        uint8_t 选中,
                        uint8_t 可见项数,
                        uint8_t 首行)
{
    uint8_t 首项 = 0U;
    uint8_t i;
    uint8_t 标题字节数;
    uint8_t 标题列;

    /* ---- 算滚动窗口 ---- */
    if (总项数 > 可见项数)
    {
        if (选中 >= 可见项数) {
            首项 = (uint8_t)(选中 - (可见项数 - 1U));
        }
        if (((uint16_t)首项 + 可见项数) > 总项数) {
            首项 = (uint8_t)(总项数 - 可见项数);
        }
    }

    显示_清屏();

    /* ---- 标题：计算 UTF-8 字符数来居中 ---- */
    标题字节数 = 0U;
    {
        const char *p = 标题;
        while (*p != '\0')
        {
            uint8_t c = (uint8_t)*p;
            标题字节数++;
            p += ((c < 0x80U) ? 1U : ((c & 0xE0U) == 0xC0U) ? 2U : 3U);
        }
    }
    if (标题字节数 > 8U) 标题字节数 = 8U;
    标题列 = (uint8_t)((16U - 标题字节数 * 2U) / 2U);
    显示_画中文(标题列, 0, 标题);

    /* ---- 菜单项 ---- */
    for (i = 0U; i < 可见项数; i++)
    {
        uint8_t 项 = (uint8_t)(首项 + i);
        uint8_t 行 = (uint8_t)(首行 + i * 2U);

        if (项 >= 总项数) {
            break;
        }

        显示_画中文(1, 行, 项名[项]);
    }

    /* ---- 选中项空心框（Marlin 风格）---- */
    {
        uint8_t 选中行 = (uint8_t)(首行 + (选中 - 首项) * 2U);
        uint8_t y0 = (uint8_t)(选中行 * 8U + 2U);
        uint8_t y1 = (uint8_t)(选中行 * 8U + 14U);
        显示_画空心框(4, y0, 123, y1);
    }

    /* ---- 滚动箭头 ---- */
    if (首项 > 0U) {
        显示_画字符(15, 首行, '^');
    }
    if (((uint16_t)首项 + 可见项数) < 总项数) {
        显示_画字符(15, (uint8_t)(首行 + (可见项数 - 1U) * 2U + 1U), 'v');
    }

    显示_刷新();
}

/**
  * @brief  子菜单界面（项目名做标题 + [运行]/[返回]）
  */
static void 菜单_画子界面(uint8_t 主菜单选中项, uint8_t 子菜单选中)
{
    char 标题[16];
    const char *源;
    char *dst;
    uint8_t len;

    /* 截取主菜单项名前几个字节做标题，防止太长 */
    /* 这里简单用 UTF-8 安全截断：最多取 4 个字符 */
    源 = 菜单表[主菜单选中项].名字;
    dst = 标题;
    len = 0U;
    while (*源 != '\0' && len < 4U)
    {
        uint8_t c = (uint8_t)*源;
        uint8_t 步进 = ((c < 0x80U) ? 1U : ((c & 0xE0U) == 0xC0U) ? 2U : 3U);
        uint8_t j;
        for (j = 0U; j < 步进 && *源 != '\0'; j++) {
            *dst++ = *源++;
        }
        len++;
    }
    *dst = '\0';

    菜单_画界面(标题, 子菜单_项名, 子菜单_项数, 子菜单选中, 子菜单_项数, 主菜单_首行);
}

/* ============================== 导航逻辑 =================================== */

/** 带滚动的上下导航 */
static uint8_t 菜单_导航(uint8_t 当前, uint8_t 总数, btn_event_t 事件)
{
    if (事件 == BTN_UP)
    {
        if (当前 == 0U) {
            return (uint8_t)(总数 - 1U);
        } else {
            return (uint8_t)(当前 - 1U);
        }
    }
    if (事件 == BTN_DOWN)
    {
        return (uint8_t)((当前 + 1U) % 总数);
    }
    return 当前;
}

/**
  * @brief  运行确认界面："执行中…"
  */
static void 菜单_执行动作(const 菜单_项 *项)
{
    显示_清屏();
    显示_画中文(0, 2, 项->名字);
    显示_画中文(2, 4, "运行中");
    显示_刷新();

    if (项->动作 != NULL) {
        项->动作();
    }
}

/* ============================== 原始值显示 ================================= */

static void 菜单_显示原始值(void)
{
    uint16_t 值[5];

    while (1)
    {
        菜单_读五路(值);
        菜单_画原始值界面(值);
        显示_画字符串(0, 7, "ANY KEY=EXIT");
        显示_刷新();

        if (按键_取事件() != BTN_NONE) {
            break;
        }
        HAL_Delay(150U);
    }
}

/* ============================== 串口标定 =================================== */

void 菜单_串口标定(void)
{
    uint16_t 值[5];

    显示_初始化();
    printf("\r\n===== 5-way IR raw values (0-4095) =====\r\n");

    while (1)
    {
        菜单_读五路(值);
        printf("c0=%4u c1=%4u c2=%4u c3=%4u c4=%4u\r\n",
               (unsigned)值[0], (unsigned)值[1], (unsigned)值[2],
               (unsigned)值[3], (unsigned)值[4]);

        菜单_画原始值界面(值);
        显示_画字符串(0, 7, "SERIAL MODE");
        显示_刷新();
        HAL_Delay(200U);
    }
}

/* ============================== 动作包装 =================================== */

static void 跑直线(void)
{
    巡线(40);
    电机_全部停止();
}

static void 跑循环(void)
{
    uint8_t i;
    for (i = 0U; i < 4U; i++)
    {
        巡线(40);
        左转();
    }
    电机_全部停止();
}

/* ============================== 主入口 ===================================== */

/**
  * @brief  主菜单循环（Marlin 风格二级菜单）
  *
  *         一级菜单：上/下选功能，确认键进入子菜单
  *         子菜单  ：[运行] 执行 / [返回] 回主菜单
  *         任意层级：长按确认键 2s 返回上一级
  */
void 菜单_运行(void)
{
    uint8_t 主选中 = 0U;
    uint8_t 子选中 = 0U;
    uint8_t 在子菜单 = 0U;

    按键_初始化();
    显示_初始化();

    /* 画出主菜单 */
    菜单_画界面("功能菜单",
                (const char *const *)菜单表,
                菜单_项数,
                主选中,
                主菜单_可见项数,
                主菜单_首行);

    while (1)
    {
        btn_event_t 事件 = 按键_取事件();

        if (事件 == BTN_NONE)
        {
            HAL_Delay(10U);
            continue;
        }

        if (事件 == BTN_BACK)
        {
            /* 长按 = 返回 */
            if (在子菜单 != 0U)
            {
                在子菜单 = 0U;
                子选中 = 0U;
                菜单_画界面("功能菜单",
                            (const char *const *)菜单表,
                            菜单_项数,
                            主选中,
                            主菜单_可见项数,
                            主菜单_首行);
                continue;
            }
            /* 主菜单时长按什么都不做，保持显示 */
            continue;
        }

        if (在子菜单 == 0U)
        {
            /* ========== 一级菜单 ========== */
            uint8_t 新选中 = 菜单_导航(主选中, 菜单_项数, 事件);

            if (新选中 != 主选中)
            {
                主选中 = 新选中;
                菜单_画界面("功能菜单",
                            (const char *const *)菜单表,
                            菜单_项数,
                            主选中,
                            主菜单_可见项数,
                            主菜单_首行);
            }
            else if (事件 == BTN_SEL)
            {
                /* 进入子菜单 */
                在子菜单 = 1U;
                子选中 = 0U;
                菜单_画子界面(主选中, 子选中);
            }
        }
        else
        {
            /* ========== 子菜单 ========== */
            uint8_t 新选中 = 菜单_导航(子选中, 子菜单_项数, 事件);

            if (新选中 != 子选中)
            {
                子选中 = 新选中;
                菜单_画子界面(主选中, 子选中);
            }
            else if (事件 == BTN_SEL)
            {
                if (子选中 == 0U)
                {
                    /* [运行]：执行动作 */
                    菜单_执行动作(&菜单表[主选中]);
                    /* 跑完回到子菜单 */
                    子选中 = 0U;
                    菜单_画子界面(主选中, 子选中);
                }
                else
                {
                    /* [返回]：回到主菜单 */
                    在子菜单 = 0U;
                    子选中 = 0U;
                    菜单_画界面("功能菜单",
                                (const char *const *)菜单表,
                                菜单_项数,
                                主选中,
                                主菜单_可见项数,
                                主菜单_首行);
                }
            }
        }

        HAL_Delay(10U);
    }
}