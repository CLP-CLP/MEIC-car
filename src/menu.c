/**
 ******************************************************************************
 * @file    menu.c
 * @brief   Marlin 风格菜单引擎 + 本车的菜单树
 *
 *  前半是引擎：菜单栈、滚动窗口、反白高亮、提示
 *  后半是菜单树：用宏把已有任务函数挂上去，任务函数一个都没改
 *
 *  显示布局（128x64，每屏 3 行 16 像素）
 *      ┌────────────────────────────┐
 *      │ 标题（整条反白）      1/8  │  16 px
 *      ├────────────────────────────┤
 *      │ ▓选中项（整行反白）     ▸  │  16 px
 *      │   其它项                    │  16 px
 *      │   其它项                    │  16 px
 *      └────────────────────────────┘
 *
 *  为什么行与行之间不会再出现半截笔画（乱码）
 *      1. 每行固定 16 像素、从 y = 0/16/32/48 开始，没有半像素错位；
 *      2. 汉字就是 16x16，正好占满自己这一行；
 *      3. 字库由 gen_font.py 生成时把墨迹限制在格子内并居中，上下左右各留
 *         余量，**画不到相邻行去**；
 *      4. 高亮改成"整行填充 + 黑字"，不再画跨越行缝的空心框。
 ******************************************************************************
 */

