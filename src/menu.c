/** 五路传感器实时 raw 值：按任意键退出 */
static void 动作_原始值(void)
{
    char 行[20];

    for (;;)
    {
        uint8_t i;

        OLED_清屏();
        OLED_显示中文串(0, 0, 文本_原始值);

        for (i = 0U; i < 5U; i++)
        {
            (void)snprintf(行, sizeof(行), "c%u %4u",
                           (unsigned)i, (unsigned)巡线_读取第几路(i));
            OLED_显示ASCII串(0, (int16_t)(16 + i * 9), 行);
        }

        OLED_刷新();

        if (按键_取事件() != BTN_NONE) {
            break;                              /* 按任意键回菜单 */
        }
        HAL_Delay(120U);
    }
}

