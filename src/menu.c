/* ============================== 私有函数声明 =============================== */

static void 菜单_显示原始值(void);      /* 菜单表里要挂它，先声明 */
static void 跑直线(void);
static void 跑循环(void);

/* ============================== 菜单表 ===================================== */
/*
 *   加/删/改选项全部只动这张表。
 *   第一列是 OLED 上显示的名字，第二列是长按确认时调用的函数（无参数无返回）。
 */

typedef struct
{
    const char *名字;           /*!< OLED 上显示的文字（ASCII） */
    void      (*动作)(void);    /*!< 长按确认时调用 */
} 菜单_项;

static const 菜单_项 菜单表[] =
{
    /*  名字              动作              说明 */
    { "1.Line Follow",  跑直线          },      /* 巡线(40) 一直走 */
    { "2.Cycle",        跑循环          },      /* 巡线 + 右转 ×4 绕一圈 */
    { "3.Reverse",      倒库            },      /* 基础任务二·倒车入库 */
    { "4.Parallel",     侧方停车        },      /* 基础任务二·侧方停车 */
    { "5.Roman Park",   任务三_定点停车 },      /* 基础任务三·定点停车 */
    { "6.Detect",       巡线检测停车    },      /* 自定义：巡线 + 检测停车 */
    { "7.Raw View",     菜单_显示原始值 },      /* 5 路 raw 实时显示（标定用）*/
    { "8.Detective",    detective       },      /* 自定义：巡线 + 检测停车 */

    /* ---- 想加东西就照下面这行的格式加，别的地方不用动 ------------------ */
    //{ "8.Turn L",     左转            },      /* 现成函数直接挂 */
    //{ "9.Line 30",    跑巡线30        },      /* 带参数的：先写包装函数 */
};

/** 表里有多少项（加行删行都不用改这里） */
#define 菜单_项数       ((uint8_t)(sizeof(菜单表) / sizeof(菜单表[0])))

/* ============================== 界面布局 =================================== */
/*  OLED 是 16 列 × 8 行字符：
 *      行 0     标题
 *      行 1~6   菜单项（最多同时显示 6 个，多了自动滚动）
 *      行 7     操作提示
 */
#define 菜单_行首       1U
#define 菜单_可见项数   6U

/* ============================== 私有函数 =================================== */

/**
  * @brief  刷新菜单界面
  * @param  选中  当前选中的项下标（0 ~ 菜单_项数-1），前缀 '>' 高亮
  * @note   项数超过 6 个时窗口自动滚动，右侧画 ^ / v 提示上下还有内容。
  */
static void 菜单_显示(uint8_t 选中)
{
    uint8_t 首项 = 0U;
    uint8_t i;

    /* ---- 算滚动窗口的第一项，保证选中项一定在屏幕上 ---- */
    if (菜单_项数 > 菜单_可见项数)
    {
        if (选中 >= 菜单_可见项数) {
            首项 = (uint8_t)(选中 - (菜单_可见项数 - 1U));
        }
        if (((uint16_t)首项 + 菜单_可见项数) > 菜单_项数) {
            首项 = (uint8_t)(菜单_项数 - 菜单_可见项数);
        }
    }

    显示_清屏();
    显示_画字符串(0, 0, " SELECT MODE");
    显示_画字符串(0, 7, "SW=SEL HOLD=GO");

    for (i = 0U; i < 菜单_可见项数; i++)
    {
        uint8_t 项 = (uint8_t)(首项 + i);
        uint8_t 行 = (uint8_t)(菜单_行首 + i);

        if (项 >= 菜单_项数) {
            break;                          /* 表里没有更多项了 */
        }

        显示_画字符(0, 行, (项 == 选中) ? '>' : ' ');
        显示_画字符串(1, 行, 菜单表[项].名字);
    }

    /* 上面 / 下面还有项时给个箭头 */
    if (首项 > 0U) {
        显示_画字符(15, 菜单_行首, '^');
    }
    if (((uint16_t)首项 + 菜单_可见项数) < 菜单_项数) {
        显示_画字符(15, (uint8_t)(菜单_行首 + 菜单_可见项数 - 1U), 'v');
    }

    显示_刷新();
}

/**
  * @brief  在指定位置画一个 0~9999 的十进制数（固定 4 位，前导补零，方便对齐）
  */
static void 菜单_画数字(uint8_t 列, uint8_t 行, uint16_t 数值)
{
    char 缓冲[5];

    缓冲[0] = (char)('0' + ((数值 / 1000U) % 10U));
    缓冲[1] = (char)('0' + ((数值 / 100U) % 10U));
    缓冲[2] = (char)('0' + ((数值 / 10U) % 10U));
    缓冲[3] = (char)('0' + (数值 % 10U));
    缓冲[4] = '\0';

    显示_画字符串(列, 行, 缓冲);
}

/**
  * @brief  把 5 路 raw 值画到 OLED 上（不含刷新，调用方自己 显示_刷新()）
  */
static void 菜单_画原始值(const uint16_t *值)
{
    uint8_t i;

    显示_清屏();
    显示_画字符串(0, 0, "RAW 0-4095");

    for (i = 0U; i < 5U; i++)
    {
        char    标签[4];
        uint8_t 行 = (uint8_t)(1U + i);

        标签[0] = 'c';
        标签[1] = (char)('0' + i);
        标签[2] = ':';
        标签[3] = '\0';

        显示_画字符串(0, 行, 标签);
        菜单_画数字(3, 行, 值[i]);
    }
}

/** 一次读完全部 5 路 */
static void 菜单_读五路(uint16_t *值)
{
    uint8_t i;

    for (i = 0U; i < 5U; i++) {
        值[i] = 巡线_读取第几路(i);
    }
}

/**
  * @brief  5 路传感器 raw 值实时显示（菜单里选到才进，按一下按键返回）
  */
static void 菜单_显示原始值(void)
{
    uint16_t 值[5];

    while (1)
    {
        菜单_读五路(值);
        菜单_画原始值(值);
        显示_画字符串(0, 7, "PRESS=EXIT");
        显示_刷新();

        /* 按任意一下（短按或长按）都退出，回菜单 */
        if (按键_取事件() != 按键_无) {
            break;
        }

        HAL_Delay(150U);        /* 刷新节奏：150ms，读数看清楚又不闪 */
    }
}

/**
  * @brief  串口标定模式：一上电就一直把 5 路 raw 值打到 USB 串口
  *
  *  - 完全不碰按键，所以按键坏了/没接也不影响标定；
  *  - 同时 OLED 上也同步显示一份，两边都能看；
  *  - 用法：插上板载 USB，用 `pio device monitor` 或任意串口助手打开那个 COM 口
  *          （波特率随便，USB CDC 不看波特率，习惯设 115200 即可）。
  *
  *  输出格式（每 200ms 一行）：
  *      c0= 200 c1= 200 c2= 200 c3= 200 c4= 200
  *  把车分别放白底 / 黑线上，记下两行数字就是标定值。
  */
void 菜单_串口标定(void)
{
    uint16_t 值[5];

    显示_初始化();

    printf("\r\n===== 5-way IR raw values (0-4095) =====\r\n");

    while (1)
    {
        菜单_读五路(值);

        printf("c0=%4u c1=%4u c2=%4u c3=%4u c4=%4u\r\n",
               (unsigned)值[0], (unsigned)值[1], (unsigned)值[2],
               (unsigned)值[3], (unsigned)值[4]);

        菜单_画原始值(值);
        显示_画字符串(0, 7, "SERIAL MODE");
        显示_刷新();

        HAL_Delay(200U);
    }
}

/* ============================== 动作包装 =================================== */
/*  需要参数的动作在这里包一层小函数，然后直接把函数名填进上面的菜单表。
 *  格式就是：  static void 名字(void) { ...要跑的东西...; }
 *  想加"以 30 的速度巡线"就照着 跑直线() 复制一个，把 40 改成 30。 */

/** 巡线一直走（速度 40） */
static void 跑直线(void)
{
    巡线(40);
    电机_全部停止();
}

/** 巡线 + 右转，绕一圈回到起点（速度 40） */
static void 跑循环(void)
{
    uint8_t i;

    for (i = 0U; i < 4U; i++)
    {
        巡线(40);
        左转();
    }

    电机_全部停止();
}

/* ============================== 对外接口 =================================== */

void 菜单_运行(void)
{
    uint8_t 选中 = 0U;

    按键_初始化();
    显示_初始化();

    菜单_显示(选中);

    while (1)
    {
        按键_事件 事件 = 按键_取事件();

        if (事件 == 按键_短按)
        {
            /* 短按：循环到下一个功能 */
            选中 = (uint8_t)((选中 + 1U) % 菜单_项数);
            菜单_显示(选中);
        }
        else if (事件 == 按键_长按)
        {
            /* 长按确认：先提示在跑哪个，再调用表里挂的动作函数 */
            显示_清屏();
            显示_画字符串(0, 2, 菜单表[选中].名字);
            显示_画字符串(0, 4, "   RUNNING...");
            显示_刷新();

            if (菜单表[选中].动作 != NULL) {
                菜单表[选中].动作();        /* 动作跑完自己返回（都是阻塞型）*/
            }

            /* 任务跑完 / 标定退出，回到菜单等下一次选择 */
            菜单_显示(选中);
        }

        HAL_Delay(10U);                 /* 轮询节奏，10ms 足够灵敏 */
    }
}






