/**
 ******************************************************************************
 * @file    menu.c
 * @brief   Marlin 风格菜单引擎：菜单栈、滚动窗口、反白高亮、提示
 *
 *  这里是**纯引擎**，只管导航/显示/按键。
 *  菜单树（有什么项、每项干什么）在 menu_tree.c 中定义。
 *
 *  显示布局（128x64，每屏 3 行 16 像素）
 *      ┌────────────────────────────┐
 *      │ 标题（整条反白）      1/8  │  16 px
 *      ├────────────────────────────┤
 *      │ ▓选中项（整行反白）     ▸  │  16 px
 *      │   其它项                    │  16 px
 *      │   其它项                    │  16 px
 *      └────────────────────────────┘
 ******************************************************************************
 */

/* Includes ------------------------------------------------------------------*/
#include "main.h"
#include "menu.h"
#include "button.h"
#include "oled.h"
#include "ir_sensor.h"

#include <stdio.h>

/* ============================== 引擎参数 =================================== */

/** 每屏显示几项（标题占 16 像素，剩下 48 像素正好 3 行 16x16 汉字） */
#define 菜单_可见行数       3U
/** 最多能进几层子菜单 */
#define 菜单_最大深度       4U

/* ============================== 引擎状态 =================================== */

static const 菜单项 *菜单_栈[菜单_最大深度];       /* 每一级的菜单表 */
static const char   *菜单_标题栈[菜单_最大深度];   /* 每一级的标题 */
static uint8_t      菜单_深度;                     /* 1 = 在主菜单 */
static uint8_t      菜单_选中;                     /* 当前选中第几项（表内下标） */
static uint8_t      菜单_首项;                     /* 屏幕上第一行是第几项 */

/* ============================== 引擎内部 =================================== */

/** 数一张菜单表有多少项（遇到 菜单项_结束 就停） */
static uint8_t 菜单_项数(const 菜单项 *表)
{
    uint8_t n = 0U;

    while ((表[n].类型 != 菜单项_结束) && (n < 100U)) {
        n++;
    }
    return n;
}

/** 当前正在显示的菜单表 */
static const 菜单项 *菜单_当前表(void)
{
    return 菜单_栈[菜单_深度 - 1U];
}

/** 跟着选中项调整滚动窗口，保证选中项一定在屏幕上 */
static void 菜单_调整滚动(void)
{
    if (菜单_选中 < 菜单_首项) {
        菜单_首项 = 菜单_选中;
    } else if (菜单_选中 >= (uint8_t)(菜单_首项 + 菜单_可见行数)) {
        菜单_首项 = (uint8_t)(菜单_选中 - 菜单_可见行数 + 1U);
    }
}

/** 简短提示：清屏 + 一行字 + 停顿（动作执行前给个反馈） */
void 菜单_提示(const char *文字, uint16_t 毫秒)
{
    OLED_清屏();
    OLED_显示中文串(0, 24, 文字);
    OLED_刷新();
    HAL_Delay(毫秒);
}

/**
  * @brief  重画当前菜单
  */
static void 菜单_重画(void)
{
    const 菜单项 *表 = 菜单_当前表();
    uint8_t      总数 = 菜单_项数(表);
    char         小字[12];
    uint8_t      行;

    OLED_清屏();

    /* ---- 标题栏：整条反白，标题用黑字 ---- */
    OLED_填充矩形(0, 0, OLED_宽 - 1, 15, OLED_亮);
    OLED_显示中文串色(2, 0, 菜单_标题栈[菜单_深度 - 1U], OLED_灭);

    /* 右上角 "第几项/共几项"，方便知道还有没有下一页 */
    (void)snprintf(小字, sizeof(小字), "%u/%u",
                   (unsigned)(菜单_选中 + 1U), (unsigned)总数);
    OLED_显示ASCII串色((int16_t)(126 - (int16_t)OLED_文本宽度(小字)), 4,
                       小字, OLED_灭);

    /* ---- 列表：每行 16 像素，选中项整行反白 ---- */
    for (行 = 0U; 行 < 菜单_可见行数; 行++)
    {
        uint8_t 下标 = (uint8_t)(菜单_首项 + 行);
        int16_t 行顶 = (int16_t)(16 + 行 * 16);
        uint8_t 高亮;

        if (下标 >= 总数) {
            break;                              /* 这一页没有更多项了 */
        }

        高亮 = (下标 == 菜单_选中) ? 1U : 0U;

        if (高亮 != 0U) {
            OLED_画矩形(0, 行顶, OLED_宽 - 1, (int16_t)(行顶 + 15), OLED_亮);
        }

        OLED_显示中文串色(2, 行顶, 表[下标].标题, OLED_亮);

        /* 返回项在文字后面画 U 形返回箭头 */
        if (表[下标].类型 == 菜单项_返回)
        {
            int16_t ax = 36;
            int16_t ay = (int16_t)(行顶 + 2);

            OLED_画线((int16_t)(ax + 2), ay,
                      (int16_t)(ax + 5), ay, OLED_亮);
            OLED_画线((int16_t)(ax + 7), ay,
                      (int16_t)(ax + 12), ay, OLED_亮);

            OLED_画线((int16_t)(ax + 12), ay,
                      (int16_t)(ax + 12), (int16_t)(ay + 10), OLED_亮);

            OLED_画线((int16_t)(ax + 12), (int16_t)(ay + 10),
                      (int16_t)(ax + 3), (int16_t)(ay + 10), OLED_亮);

            OLED_画线((int16_t)(ax + 1), (int16_t)(ay + 10),
                      (int16_t)(ax + 3), (int16_t)(ay + 8), OLED_亮);
            OLED_画线((int16_t)(ax + 1), (int16_t)(ay + 10),
                      (int16_t)(ax + 3), (int16_t)(ay + 12), OLED_亮);
        }

        /* 子菜单在右侧标一个 ">" */
        if (表[下标].类型 == 菜单项_子菜单)
        {
            OLED_显示ASCII串色(120, (int16_t)(行顶 + 4), ">", OLED_亮);
        }
    }

    OLED_刷新();
}

/** 处理一个按键事件 */
static void 菜单_处理(btn_event_t 事件)
{
    const 菜单项 *表 = 菜单_当前表();
    uint8_t      总数 = 菜单_项数(表);
    const 菜单项 *项;

    if (总数 == 0U) {
        return;
    }
    项 = &表[菜单_选中];

    switch (事件)
    {
        case BTN_UP:
            菜单_选中 = (菜单_选中 == 0U) ? (uint8_t)(总数 - 1U)
                                          : (uint8_t)(菜单_选中 - 1U);
            菜单_调整滚动();
            菜单_重画();
            break;

        case BTN_DOWN:
            菜单_选中 = (uint8_t)((菜单_选中 + 1U) % 总数);
            菜单_调整滚动();
            菜单_重画();
            break;

        case BTN_SEL:
            switch (项->类型)
            {
                case 菜单项_子菜单:
                    if ((项->子菜单 != 0) && (菜单_深度 < 菜单_最大深度))
                    {
                        菜单_栈[菜单_深度] = 项->子菜单;
                        菜单_标题栈[菜单_深度] = 项->标题;
                        菜单_深度++;
                        菜单_选中 = 0U;
                        菜单_首项 = 0U;
                    }
                    菜单_重画();
                    break;

                case 菜单项_命令:
                    if (项->动作 != 0) {
                        项->动作();                 /* 跑任务，跑完自己回到菜单 */
                    }
                    菜单_重画();
                    break;

                case 菜单项_返回:
                    if (菜单_深度 > 1U)
                    {
                        菜单_深度--;
                        菜单_选中 = 0U;
                        菜单_首项 = 0U;
                    }
                    菜单_重画();
                    break;

                default:
                    break;
            }
            break;

        /* 长按确定键 = 返回上一级 */
        case BTN_BACK:
            if (菜单_深度 > 1U)
            {
                菜单_深度--;
                菜单_选中 = 0U;
                菜单_首项 = 0U;
                菜单_重画();
            }
            break;

        default:
            break;
    }
}

/* ============================== 串口标定 =================================== */

void 菜单_串口标定(void)
{
    char 行[20];

    OLED_初始化();
    printf("\r\n===== 5-way IR raw values (0-4095) =====\r\n");

    for (;;)
    {
        uint8_t i;

        OLED_清屏();
        OLED_显示ASCII串(0, 0, "SERIAL MODE");
        for (i = 0U; i < 5U; i++)
        {
            (void)snprintf(行, sizeof(行), "c%u %4u",
                           (unsigned)i, (unsigned)巡线_读取第几路(i));
            OLED_显示ASCII串(0, (int16_t)(16 + i * 9), 行);
        }
        OLED_刷新();

        printf("c0=%4u c1=%4u c2=%4u c3=%4u c4=%4u\r\n",
               (unsigned)巡线_读取第几路(0), (unsigned)巡线_读取第几路(1),
               (unsigned)巡线_读取第几路(2), (unsigned)巡线_读取第几路(3),
               (unsigned)巡线_读取第几路(4));

        HAL_Delay(200U);
    }
}

/* ============================== 对外接口 =================================== */

void 菜单_复位(void)
{
    菜单_深度 = 1U;
    菜单_栈[0] = 菜单树_取主表();
    菜单_标题栈[0] = 菜单树_取主标题();
    菜单_选中 = 0U;
    菜单_首项 = 0U;
}

void 菜单_运行(void)
{
    按键_初始化();
    OLED_初始化();
    菜单_复位();
    菜单_重画();

    for (;;)
    {
        btn_event_t 事件 = 按键_取事件();

        if (事件 != BTN_NONE) {
            菜单_处理(事件);
        }

        HAL_Delay(10U);                         /* 10 ms 轮询，按下去就有反应 */
    }
}