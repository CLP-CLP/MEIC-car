/**
 ******************************************************************************
 * @file    menu.c
 * @brief   二级菜单：三键（上 / 下 / 确认）+ OLED 中文显示 + 表驱动
 *
 *  操作
 *      上键短按       光标上移（循环）
 *      下键短按       光标下移（循环）
 *      确认键短按     进子菜单 / 执行
 *      确认键长按 2s  返回上一级
 *
 *  界面布局（128x64，16x16 汉字 = 2 列 x 2 行）
 *  ---------------------------------------------------------------
 *      Row 0-1 : 标题（16x16，按字符数居中）
 *      Row 2-3 : 菜单项 0
 *      Row 4-5 : 菜单项 1     一屏 3 项，多了自动滚动
 *      Row 6-7 : 菜单项 2     最右列画 ^ / v 滚动提示
 *
 *  为什么行与行之间一定是干净的
 *  ---------------------------------------------------------------
 *  1. 每项固定占 **2 行（16 像素）**，行与行之间天然留出 2 行空白；
 *  2. 字库由 gen_font.py 生成时把每个汉字的墨迹硬限制在 14x14 并居中
 *     放进 16x16 —— 上下左右各留 1 像素，**画不进相邻行**；
 *  3. 选中框只画在这一项自己的 2 行内，边框线不会压到下一行文字上。
 *
 *  加/删/改菜单项：只在 菜单表[] 里加一行即可。
 ******************************************************************************
 */

