/* 这里只负责"提示 + 调用原工程已有的任务函数"，任务实现一个字都没改 */

/** 巡线：沿黑线一直走，到拐角自动停 */
static void 动作_巡线(void)
{
    菜单_提示(文本_巡线, 500U);
    巡线(40);
    电机_全部停止();
}

/** 循环：巡线 + 左转，跑 4 条边 */
static void 动作_循环(void)
{
    uint8_t 边;

    菜单_提示(文本_循环, 500U);
    for (边 = 0U; 边 < 4U; 边++)
    {
        巡线(40);
        电机_全部停止();
        HAL_Delay(200U);
        if (边 < 3U) {
            左转();
        }
    }
}

