/* ================== 基础任务三：罗马数字识别定点停车 ======================== */

/*
 *  题目：从 BC 边车库出发，识别车前的罗马数字卡片，停在对应点。
 *        I -> A 点    III -> B 点    V -> C 点    VII -> D 点
 *
 *  场地（见题目图 1 / 图 2）：A 左上、B 右上、C 右下、D 左下，BC 是右边那条边。
 *  车停在 BC 边车库（正方形内侧），车头朝正方形外、正对着卡片。
 *
 *  所以：
 *      车头朝外时，左转 = 朝 B（图上方），右转 = 朝 C（图下方）
 *      从 BC 边中点出发，往 B 走：第 1 个拐角是 B，再过一条边第 2 个拐角是 A
 *                        往 C 走：第 1 个拐角是 C，再过一条边第 2 个拐角是 D
 *
 *  整道题就只剩两件事：往哪边走、数几个拐角。
 */

#define 任务三_认卡超时毫秒   8000U    /* 最多等 8 秒认卡片；认不出来就原地不动 */
#define 任务三_巡线速度       40       /* 沿边巡线的速度 */
#define 任务三_出库速度       35       /* 从车库开出来找黑线的速度 */
#define 任务三_出库超时毫秒   1500U    /* 出库最多开这么久，找不到线就停下（防跑飞） */
#define 任务三_触线阈值       600U     /* "刚碰到线"的阈值：必须比 1500 小，
                                          因为 左转()/右转() 等的是中间路 >= 1500 */

/**
  * @brief  在车库里读出卡片，换算成目标停车点
  * @retval 'A' / 'B' / 'C' / 'D'；认不出来返回 0
  */
static uint8_t 任务三_读卡片(void)
{
    协议_结果 卡片;

    if (协议_等待卡片(任务三_认卡超时毫秒, &卡片) == 0U) {
        return 0U;                      /* 认不出来：后面会原地不动，比乱跑安全 */
    }

    switch (卡片.罗马数字)
    {
        case 1U:  return 'A';           /* I   -> A 点 */
        case 3U:  return 'B';           /* III -> B 点 */
        case 5U:  return 'C';           /* V   -> C 点 */
        case 7U:  return 'D';           /* VII -> D 点 */
        default:  return 0U;
    }
}

/**
  * @brief  出库上赛道：直行到刚压上 BC 黑线，再原地转 90° 摆到沿边方向
  * @param  往B走 1 = 朝 B（左转），0 = 朝 C（右转）
  */
static void 任务三_出库(uint8_t 往B走)
{
    uint32_t 出发时刻 = HAL_GetTick();

    电机_设置双轮(任务三_出库速度, 任务三_出库速度);

    /* 等中间三路里任意一路刚碰到黑线。阈值用 600 而不是 1500 是有意的：
       左转()/右转() 的退出条件是"中间路 >= 1500"，如果现在就压到 1500，
       它们会立刻返回、一点都不转。 */
    while ((巡线_读取第几路(1) < 任务三_触线阈值)
        && (巡线_读取第几路(2) < 任务三_触线阈值)
        && (巡线_读取第几路(3) < 任务三_触线阈值)
        && ((uint32_t)(HAL_GetTick() - 出发时刻) < 任务三_出库超时毫秒))
    {
        /* 等压线 */
    }

    电机_全部停止();
    HAL_Delay(100U);

    /* 车头朝外：左转朝 B，右转朝 C */
    if (往B走 != 0U) {
        左转();
    } else {
        右转();
    }
}

/**
  * @brief  基础任务三：从 BC 边车库出发，识别车前罗马数字，停在对应点
  */
void 任务三_定点停车(void)
{
    uint8_t 目标点;
    uint8_t 往B走;          /* 1 = 朝 B（图上方），0 = 朝 C（图下方） */
    uint8_t 拐角数;         /* 还要走过几个拐角才停 */

    电机_全部停止();
    HAL_Delay(500U);                        /* 停稳，让 OpenMV 对准卡片 */

    /* ---- 1. 读卡片 ---- */
    目标点 = 任务三_读卡片();

    if (目标点 == 0U) {
        return;                             /* 没认出来：原地不动 */
    }

    /* ---- 2. 卡片 -> 出发方向 + 要过的拐角数 ---- */
    if ((目标点 == 'A') || (目标点 == 'B'))
    {
        往B走  = 1U;
        拐角数 = (目标点 == 'B') ? 1U : 2U;     /* B 是第 1 个拐角，A 是第 2 个 */
    }
    else
    {
        往B走  = 0U;
        拐角数 = (目标点 == 'C') ? 1U : 2U;     /* C 是第 1 个拐角，D 是第 2 个 */
    }

    /* ---- 3. 出库，把车摆到 BC 边上 ---- */
    任务三_出库(往B走);

    /* ---- 4. 沿边巡线，数拐角；到第 拐角数 个拐角就停 ---- */
    while (拐角数 > 0U)
    {
        巡线(任务三_巡线速度);               /* 走到拐角会自动停车并返回 */

        拐角数--;

        if (拐角数 > 0U)                     /* 还没到，拐过去继续下一条边 */
        {
            if (往B走 != 0U) {
                左转();
            } else {
                右转();
            }
        }
    }

    电机_全部停止();                         /* 停稳在目标点上 */
}

