/** 发一条命令（控制字节 0x00） */
static void 显示_写命令(uint8_t 命令)
{
    (void)HAL_I2C_Mem_Write(&显示_I2C, 显示_I2C地址, 0x00,
                            I2C_MEMADD_SIZE_8BIT, &命令, 1, 100U);
}

/** 发一段数据（控制字节 0x40） */
static void 显示_写数据(const uint8_t *数据, uint16_t 长度)
{
    (void)HAL_I2C_Mem_Write(&显示_I2C, 显示_I2C地址, 0x40,
                            I2C_MEMADD_SIZE_8BIT, (uint8_t *)数据, 长度, 1000U);
}

