/* ============================== 绘图接口 =================================== */

void 显示_清屏(void)
{
    memset(显示_帧缓冲, 0x00, sizeof(显示_帧缓冲));
}

void 显示_刷新(void)
{
    /* 设置寻址范围：列 0..127、页 0..7 */
    uint8_t 寻址命令[] = {
        0x21, 0x00, 0x7F,       /* 列地址 */
        0x22, 0x00, 0x07        /* 页地址 */
    };
    uint8_t *指针 = 显示_帧缓冲;
    uint16_t 剩余 = (uint16_t)sizeof(显示_帧缓冲);
    uint8_t i;

    for (i = 0U; i < sizeof(寻址命令); i++) {
        显示_写命令(寻址命令[i]);
    }

    /* 分块发送，避免单次 I2C 传输过长 */
    while (剩余 > 0U)
    {
        uint16_t 本次 = (剩余 > 128U) ? 128U : 剩余;
        显示_写数据(指针, 本次);
        指针 += 本次;
        剩余 -= 本次;
    }
}

