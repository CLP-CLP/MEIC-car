/* ============================== 参数 ======================================= */
/* 按你的实测（白 ~200 / 黑 ~750）取中间值；换场地就改这几个数 */

#define 压线阈值      450     /* 读数 >= 这个值 = 压黑线 */
#define 巡线速度      20      /* 正常巡线速度 */
#define 检测速度      10    /* 检测状态的低速 */
#define 控制周期毫秒  5U
#define 侧方判定毫秒  2000U   /* 检测状态计时 > 2 秒判为侧方，<= 2 秒判为倒库 */

/* 五路二值位图：bit0=第1路(PA0,-60mm) ... bit4=第5路(PA4,+60mm)，1 = 压黑线。
   0x07 / 0x1C 这两个形态只有"垂直横线"（库边线）压过来时才会出现：
   正常沿边巡线时中间最多压 1~2 路，两侧外侧探头是碰不到线的。 */
#define 图_全白       0x00U
#define 图_左三黑     0x07U   /* 第 1、2、3 路黑，第 4、5 路白（横线从左边来）*/
#define 图_右三黑     0x1CU   /* 第 3、4、5 路黑，第 1、2 路白（横线从右边来）*/
#define 图_全黑       0x1FU   /* 五路全黑（备用，正常不该出现） */

/* ============================== 私有类型 =================================== */

typedef enum
{
    状态_巡线 = 0,
    状态_检测,
    状态_完成
} 流程状态;

/* ============================== 私有函数 =================================== */

/** 读 5 路，返回二值位图（1 = 压黑线）；巡线() 的声明在 line_follow.h 里 */
static uint8_t 读位图(void)
{
    uint8_t 图 = 0U;

    if (巡线_读取第几路(0) >= 压线阈值) 图 |= 0x01U;
    if (巡线_读取第几路(1) >= 压线阈值) 图 |= 0x02U;
    if (巡线_读取第几路(2) >= 压线阈值) 图 |= 0x04U;
    if (巡线_读取第几路(3) >= 压线阈值) 图 |= 0x08U;
    if (巡线_读取第几路(4) >= 压线阈值) 图 |= 0x10U;

    return 图;
}

/**
  * @brief  向左倒库（固定动作，参数按你的库位几何调）
  */
static void 向左倒库(void)
{
    电机_设置双轮(-20, -40);   /* 左轮慢、右轮快，倒着往左摆 */
    HAL_Delay(800);
    电机_全部停止();
}

/**
  * @brief  向右倒库（固定动作，参数按你的库位几何调）
  */
static void 向右倒库(void)
{
    电机_设置双轮(-40, -20);   /* 倒着往右摆 */
    HAL_Delay(800);
    电机_全部停止();
}

/**
  * @brief  向左侧方（固定动作，参数按你的库位几何调）
  */
static void 向左侧方(void)
{
    电机_设置双轮(-40, -40);   /* 先直线倒一段 */
    HAL_Delay(500);
    电机_设置双轮(-40, 10);    /* 倒着往左摆 */
    HAL_Delay(700);
    电机_设置双轮(-20, -20);   /* 回正再倒一点 */
    HAL_Delay(400);
    电机_全部停止();
}

/**
  * @brief  向右侧方（固定动作，参数按你的库位几何调）
  */
static void 向右侧方(void)
{
    电机_设置双轮(-40, -40);
    HAL_Delay(500);
    电机_设置双轮(10, -40);    /* 倒着往右摆 */
    HAL_Delay(700);
    电机_设置双轮(-20, -20);
    HAL_Delay(400);
    电机_全部停止();
}

