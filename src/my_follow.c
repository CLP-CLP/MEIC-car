/**
 ******************************************************************************
 * @file    my_follow.c
 * @brief   巡线 + 检测停车（用户自定义功能）
 *
 *  流程
 *      菜单选中 -> 延迟 2 秒 -> 循环 { 读位图
 *          -> 位图 == 左三黑 / 右三黑（垂直黑线 = 库边横线）? 进检测状态
 *          -> 否则 巡线(巡线速度)（阻塞：走到拐角/丢线才返回）}
 *
 *      检测状态：先降速巡线（巡线(检测速度)），再按位图分支：
 *          前方全白   -> 拐角：按来向转弯，回去继续巡线
 *          又见左三黑 -> 向左倒库 / 向左侧方
 *          又见右三黑 -> 向右倒库 / 向右侧方
 *
 *  巡线() 由 line_follow.c 提供：模拟量算位置 + 查表出差速，遇到拐角形态
 *  （外侧 1/5 + 内侧 2/3/4 同时压黑）立刻停车返回。
 *
 *  传感器下标（沿用 ir_sensor.h；实际安装是 1  234  5，中间三路间距 20mm）：
 *      c0=第1路(PA0,-60mm)  c1=第2路(PA1,-20mm)  c2=第3路(PA2,0mm)
 *      c3=第4路(PA3,+20mm)  c4=第5路(PA4,+60mm)
 ******************************************************************************
 */

