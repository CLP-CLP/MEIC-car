/**
 ******************************************************************************
 * @file    turn.c
 * @brief   左转 / 右转 —— 原地转 90°（两段式：先脱旧线，再上新线）
 *
 *  调用时机：`巡线()` 在拐角停车返回后调用。那时车正压在角上，
 *  中间三路本来就是黑的，所以绝不能"一把就以压线为退出条件"。
 * ==========================================================================
 */

/* Includes ------------------------------------------------------------------*/
#include "main.h"
#include "turn.h"
#include "motor.h"
#include "ir_sensor.h"
#include "gray_calib.h"     /* 每路阈值：灰度_各路阈值[i] */

/* ============================== 可调参数 =================================== */

/** 转弯时电机的原地转动力度（0~100，已做死区补偿） */
#define 转弯_原地转速      30

/** 每个阶段最多转多久（毫秒），防止某阶段一直不满足而卡死 */
#define 转弯_超时毫秒      3000U

/* ============================== 私有工具 =================================== */

/** 中间三路(第 1/2/3 路)任意一路压黑 -> 认为车正压在线交叉口 */
#define 转弯_中间压线() ( \
    (巡线_读取第几路(1) >= 灰度_各路阈值[1]) || \
    (巡线_读取第几路(2) >= 灰度_各路阈值[2]) || \
    (巡线_读取第几路(3) >= 灰度_各路阈值[3]) )

/**
  * @brief  转向的两段式流程（非阻塞，用 HAL_GetTick() 计时）
  * @param  左占空比  原地左转传负/右正，右转反过来
  * @note   巡线() 停在拐角时中间三路已经是黑的，不能一上来就用
  *         "中间压线"当退出条件（否则一秒就返回、一点不转）。
  *         所以先转出旧线（中间全不黑），再转上新的线（中间重新变黑）。
  */
static void 转弯_原地(uint16_t 左占空比, uint16_t 右占空比)
{
    uint32_t 开始;

    /* 阶段一：先原地转到中间三路完全脱离黑线（把压在角上的旧线甩开） */
    电机_设置双轮((int16_t)左占空比, (int16_t)右占空比);
    开始 = HAL_GetTick();
    while (转弯_中间压线()
           && (uint32_t)(HAL_GetTick() - 开始) < 转弯_超时毫秒)
    {
        /* 空转等待脱线 */
    }

    /* 阶段二：继续同方向转，直到中间三路重新压上黑线（对准新边） */
    开始 = HAL_GetTick();
    while (!转弯_中间压线()
           && (uint32_t)(HAL_GetTick() - 开始) < 转弯_超时毫秒)
    {
        /* 空转等待重新压线 */
    }

    电机_全部停止();
}

void 左转(void)
{
    转弯_原地(-转弯_原地转速, 转弯_原地转速);   /* 左轮退、右轮进 = 原地左转 */
}

void 右转(void)
{
    转弯_原地(转弯_原地转速, -转弯_原地转速);   /* 左轮进、右轮退 = 原地右转 */
}