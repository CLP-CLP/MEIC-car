/**
 ******************************************************************************
 * @file    turn.c
 * @brief   左转 / 右转 —— 平滑渐进转弯
 *
 *  改进要点（相比旧版）：
 *    1. 初始 200ms 原地等待 → 慢速蠕行（车不停，观感流畅）
 *    2. 速度跳变 20→10→0 → 渐进加减速（不再生硬切换）
 *    3. 检测到线即急刹 → 渐减速 + 缓停（50ms 渐降到零）
 *    4. 共用辅助函数，减少重复代码
 ******************************************************************************
 */

/* Includes ------------------------------------------------------------------*/
#include "main.h"
#include "turn.h"
#include "motor.h"
#include "ir_sensor.h"
#include "gray_calib.h"

void (*转向_每帧回调)(void) = NULL;

/* ========================== 内部辅助 ====================================== */

#define 转向_刷新限速毫秒   100U   /* 回调最小间隔 */

/**
  * @brief  如果到了刷新间隔，调用一次屏幕刷新回调
  */
static void 转向_刷屏(uint32_t *上次, uint32_t 现在)
{
    if (转向_每帧回调 == NULL) return;
    if ((uint32_t)(现在 - *上次) < 转向_刷新限速毫秒) return;
    *上次 = 现在;
    转向_每帧回调();
}

/**
  * @brief  从当前速度渐降到零（耗时约 50ms），期间继续刷屏
  * @param  电机号  正在转的那一路电机
  */
static void 转向_渐停(uint8_t 电机号, uint32_t *上次刷新)
{
    int16_t 当前;
    uint32_t now;

    /* 从当前实际转速开始渐降 */
    if (电机号 == 电机_左)
        当前 = 电机_最后左速度;
    else
        当前 = 电机_最后右速度;

    if (当前 <= 0) 当前 = 8;   /* 兜底 */

    while (当前 > 0) {
        当前 -= 3;
        if (当前 < 0) 当前 = 0;

        if (电机号 == 电机_左)
            电机_转速(电机_左, 当前);
        else
            电机_转速(电机_右, 当前);

        HAL_Delay(18U);

        now = HAL_GetTick();
        转向_刷屏(上次刷新, now);
    }

    电机_全部停止();
}

/* =============== 判断宏：探头是否压线 ===============
 *  外侧 = 最左(0) 或 最右(4) 探头压黑    → 线在侧面
 *  中间 = 探头 1/2/3 任意一路压黑         → 线回到中间 = 转到位
 *
 *  注意：用 灰度_各路阈值（常规阈值）判定，和旧版一致。
 */
#define 外侧压线(r)  ((r)[0] >= 灰度_各路阈值[0] || (r)[4] >= 灰度_各路阈值[4])
#define 中间压线(r)  ((r)[1] >= 灰度_各路阈值[1] || \
                       (r)[2] >= 灰度_各路阈值[2] || \
                       (r)[3] >= 灰度_各路阈值[3])

/* ============================== 左转 ====================================== */

void 左转(void)
{
    uint32_t 开始, 现在, 上次刷新 = 0U;
    uint16_t 原始值[5];
    int16_t  目标速度  = 25;     /* 目标巡航速度 */
    int16_t  当前速度  = 5;      /* 当前实际速度（渐进加速） */

    /* ---- 阶段 1：慢速蠕行过角（原来空转 200ms）---- */
    开始 = HAL_GetTick();
    while ((uint32_t)(HAL_GetTick() - 开始) < 200U) {
        电机_转速(电机_左, 5);
        电机_转速(电机_右, 5);
        现在 = HAL_GetTick();
        转向_刷屏(&上次刷新, 现在);
    }

    /* ---- 阶段 2：渐进加速 + 转向 ---- */
    开始 = HAL_GetTick();
    当前速度 = 5;
    电机_转速(电机_左, 0);        /* 左轮刹死，右轮前推 = 原地左转 */

    while (1) {
        巡线_取最新帧(原始值);
        现在 = HAL_GetTick();
        转向_刷屏(&上次刷新, 现在);

        /* --- 线回到中间：转到位，渐停 --- */
        if (中间压线(原始值)) {
            转向_渐停(电机_右, &上次刷新);
            return;
        }

        /* --- 外侧探头碰线 → 降速 --- */
        if (外侧压线(原始值)) {
            当前速度 = 10;
        }
        /* --- 还没看到线 → 渐进加速到目标 --- */
        else if (当前速度 < 目标速度) {
            当前速度 += 2;
            if (当前速度 > 目标速度) 当前速度 = 目标速度;
        }

        电机_转速(电机_右, 当前速度);
    }
}

